/* ============================================================================
   docs/cfb-altitude/BACKTEST.md, rendered from football/validation/
   altitude_cfb.json. Every number in the report is read from the validation
   record; nothing is typed here, so the report cannot drift from the run.
   ========================================================================== */
'use strict';

const f2 = x => (x == null || !isFinite(x) ? '—' : (+x).toFixed(2));
const f3 = x => (x == null || !isFinite(x) ? '—' : (+x).toFixed(3));
const s2 = x => (x == null || !isFinite(x) ? '—' : (x >= 0 ? '+' : '−') + Math.abs(+x).toFixed(2));
const s3 = x => (x == null || !isFinite(x) ? '—' : (x >= 0 ? '+' : '−') + Math.abs(+x).toFixed(3));
const ci = c => (c && c.length === 2 ? '[' + s2(c[0]) + ', ' + s2(c[1]) + ']' : '—');
const ci3 = c => (c && c.length === 2 ? '[' + s3(c[0]) + ', ' + s3(c[1]) + ']' : '—');
const pv = p => (p == null ? '—' : (+p).toFixed(3));
const n = x => (x == null ? '—' : Number(x).toLocaleString('en-US'));
const yes = b => (b ? 'PASS' : 'FAIL');

function table(head, rows) {
  return '| ' + head.join(' | ') + ' |\n|' + head.map(() => '---').join('|') + '|\n'
    + rows.map(r => '| ' + r.join(' | ') + ' |').join('\n') + '\n';
}

function render(v, p) {
  const sel = v.walk_forward[v.selected];
  const out = [];
  out.push('# CFB Altitude & Travel — historical validation');
  out.push('');
  out.push('Generated by `football/altitude/research/run.js` from `football/validation/altitude_cfb.json` ('
    + v.generated_at.slice(0, 10) + '). Do not edit by hand: rerun the harness. Gates declared ' + v.declared_gates
    + ' in `football/altitude/research/gates.js`.');
  out.push('');
  out.push('## Verdict');
  out.push('');
  out.push('**Status: ' + v.status + '. Points applied: ' + (v.points_applied ? 'YES' : '0.0') + '.** '
    + 'Statistical support: **' + v.support_state.replace('_', ' ') + '**.');
  out.push('');
  out.push('> ' + v.support_text);
  out.push('');
  out.push('The selected candidate (`' + v.selected + '`, chosen on the 2014–2021 walk-forward only) was then scored on 2022–2025, which nothing was tuned on. '
    + 'On the ' + n(sel.confirm.affected.n) + ' confirmation games it touched, MAE went from ' + f3(sel.confirm.affected.baseline.mae)
    + ' to ' + f3(sel.confirm.affected.arm.mae) + ' (improvement ' + s3(sel.confirm.affected.paired.mae_improvement)
    + ', 95% CI ' + ci3(sel.confirm.affected.paired.ci95) + ', paired p = ' + pv(sel.confirm.affected.paired.p) + '). '
    + 'The baseline-preserving fallback therefore stands: V1’s published number is unchanged, and the altitude term runs in SHADOW.');
  out.push('');
  out.push('## What was tested, against what');
  out.push('');
  out.push('- **Baseline:** ' + v.baseline.engine + ', replayed from ' + v.baseline.replay.replay_from + ' (' + n(v.baseline.replay.n)
    + ' FBS-vs-FBS games projected, ' + n(v.baseline.replay.refused) + ' refused for an unrated team). ' + v.baseline.note + '.');
  out.push('- **Residual:** final home margin minus V1’s pregame fair margin. Each candidate is a regression of that residual on pre-registered altitude terms plus an intercept; the intercept absorbs V1’s general home lean and is **never** part of the adjustment, so the altitude term cannot double-count home field.');
  out.push('- **Estimation:** OLS for inference with standard errors clustered by host venue, ridge for the estimate (penalty chosen by forward-chaining inside the training seasons only), then an uncertainty shrink of t²/(1+t²) per coefficient. A term with fewer than 30 games or 5 host venues is held at zero.');
  out.push('- **Market:** ' + v.market.source + '. ' + v.market.lines + ' Licence: ' + v.market.licence + '.');
  out.push('- **Altitude:** `football/altitude/engine.js` on the schedule’s venue ids and `football/altitude/venues.json`, the same function the live page calls.');
  out.push('');
  out.push('### Coverage');
  out.push('');
  const c = v.coverage;
  out.push(table(['games', 'non-neutral', 'usable non-neutral', 'with close', 'with open', '3,000+ ft visits', 'mountain hosts'],
    [[n(c.games), n(c.non_neutral), n(c.usable_non_neutral), n(c.with_close), n(c.with_open), n(c.high_gain_games), n(c.high_gain_hosts)]]));
  if (c.unusable_reasons && c.unusable_reasons.length) {
    out.push('Why a non-neutral game had no usable altitude context (top reasons):');
    out.push('');
    c.unusable_reasons.forEach(([k, m]) => out.push('- ' + m + ' × ' + k));
    out.push('');
  }
  out.push('Play-level aggregates (for the play-load and opponent-pace interactions) exist for ' + (v.play_load_seasons ? v.play_load_seasons.join('–') : 'no seasons') + ' only.');
  out.push('');

  out.push('## Full-sample estimates (every season, in-sample)');
  out.push('');
  out.push('Home-margin points: **+ means the visitor did worse than V1 expected**. These are associations conditional on V1, not out-of-sample results.');
  out.push('');
  const rows = [];
  Object.keys(v.full_sample).forEach(cid => {
    const fs = v.full_sample[cid];
    if (!fs.fitted) { rows.push(['`' + cid + '`', 'not fitted', '', '', '', '', '', '']); return; }
    fs.coefficients.forEach((k, i) => rows.push([i === 0 ? '`' + cid + '`' + (fs.eligible ? '' : ' *') : '', '`' + k.feature + '`',
      k.fitted ? s2(k.ols) : 'held at 0', k.fitted ? f2(k.se) : '—', k.fitted ? ci(k.ci95) : '—', n(k.support_games) + ' / ' + n(k.support_venues),
      i === 0 ? pv(fs.wild_p_main) : '', k.fitted ? s2(k.final) : '0']));
  });
  out.push(table(['candidate', 'term', 'coef', 'SE', '95% CI', 'games / venues', 'wild p (main)', 'shrunk'], rows));
  out.push('\\* not eligible to price: ' + Object.keys(v.full_sample).filter(cid => v.full_sample[cid].fitted && !v.full_sample[cid].eligible)
    .map(cid => '`' + cid + '` (' + v.full_sample[cid].why_ineligible + ')').join('; ') + '.');
  out.push('');
  out.push('### Double counting and travel');
  out.push('');
  const dc = v.double_counting;
  const dcr = (label, arr) => arr.map((k, i) => [i === 0 ? label : '', '`' + k.feature + '`', s2(k.ols), f2(k.se), ci(k.ci95)]);
  out.push(table(['fit', 'term', 'coef', 'SE', '95% CI'],
    dcr('host venue only', dc.host_only).concat(dcr('host + visitor gain', dc.host_plus_gain), dcr('host + gain + travel', dc.host_gain_travel || []))));
  out.push(dc.reading);
  out.push('');

  out.push('## Walk-forward: every candidate');
  out.push('');
  out.push('Each season is predicted by a fit on the seasons before it. Improvement = baseline MAE − candidate MAE on the games the candidate changed (positive is better).');
  out.push('');
  const wfRows = Object.keys(v.walk_forward).map(cid => {
    const w = v.walk_forward[cid];
    return ['`' + cid + '`' + (cid === v.selected ? ' **(selected)**' : ''),
      n(w.select.affected.n), s3(w.select.affected.paired.mae_improvement), pv(w.select.affected.paired.p), s3(w.select.all.paired.mae_improvement),
      n(w.confirm.affected.n), s3(w.confirm.affected.paired.mae_improvement), ci3(w.confirm.affected.paired.ci95), pv(w.confirm.affected.paired.p)];
  });
  out.push(table(['candidate', 'select n', 'select Δ (affected)', 'p', 'select Δ (all games)', 'confirm n', 'confirm Δ (affected)', 'confirm 95% CI', 'p'], wfRows));
  out.push('Selection rule: ' + v.selection_rule + '.');
  out.push('');

  out.push('## The selected candidate, scored');
  out.push('');
  const ev = (w, label) => {
    const a = w.affected, al = w.all;
    return [
      [label + ' — affected', n(a.n), f3(a.baseline.mae) + ' → ' + f3(a.arm.mae), f3(a.baseline.rmse) + ' → ' + f3(a.arm.rmse),
        s3(a.baseline.bias) + ' → ' + s3(a.arm.bias), f3(a.prob_baseline.brier) + ' → ' + f3(a.prob_arm.brier),
        f3(a.prob_baseline.log_loss) + ' → ' + f3(a.prob_arm.log_loss), f3(a.prob_baseline.ece) + ' → ' + f3(a.prob_arm.ece),
        (a.ats_baseline.win_pct == null ? '—' : f2(a.ats_baseline.win_pct) + '%') + ' → ' + (a.ats_arm.win_pct == null ? '—' : f2(a.ats_arm.win_pct) + '%') + ' (n ' + n(a.ats_arm.n) + ')'],
      [label + ' — all games', n(al.n), f3(al.baseline.mae) + ' → ' + f3(al.arm.mae), f3(al.baseline.rmse) + ' → ' + f3(al.arm.rmse),
        s3(al.baseline.bias) + ' → ' + s3(al.arm.bias), f3(al.prob_baseline.brier) + ' → ' + f3(al.prob_arm.brier),
        f3(al.prob_baseline.log_loss) + ' → ' + f3(al.prob_arm.log_loss), f3(al.prob_baseline.ece) + ' → ' + f3(al.prob_arm.ece), '—']
    ];
  };
  out.push(table(['window', 'n', 'MAE', 'RMSE', 'bias (margin − pred)', 'Brier', 'log loss', 'ECE', 'ATS vs close'],
    ev(sel.select, '2014–2021').concat(ev(sel.confirm, '2022–2025'))));
  out.push('Bias is final margin minus prediction; ATS is the side each projection prefers against the archive close (ties and zero-gap games excluded).');
  out.push('');
  out.push('Per confirmation season, affected games:');
  out.push('');
  out.push(table(['season', 'n', 'MAE before', 'MAE after'], sel.confirm.affected.per_season.map(r => [r.season, n(r.n), f3(r.mae_before), f3(r.mae_after)])));
  const lm = sel.pooled.affected.line_move;
  out.push('**Opener to close.** On ' + n(lm.n) + ' affected games with both lines (2014–2025), the market moved toward the side the altitude term favours in '
    + (lm.toward_pct == null ? '—' : f2(lm.toward_pct) + '%') + ' of the ' + n(lm.moved) + ' games that moved (mean ' + s3(lm.mean_points_toward)
    + ' pts toward it). Near 50% means the term does not anticipate the market.');
  out.push('');

  out.push('## Subgroups (all seasons, non-neutral, usable)');
  out.push('');
  out.push('V1 residual = final home margin − V1 pregame margin; close residual = final home margin − closing home line. Positive = the visitor did worse than the number. 95% intervals by host-venue cluster bootstrap.');
  out.push('');
  out.push(table(['group', 'n', 'host venues', 'V1 residual', '95% CI', 'V1 MAE', 'n with close', 'close residual', '95% CI', 'close MAE', 'visitor covers (p vs 50%)'],
    v.subgroups.map(g => [g.group, n(g.n), n(g.host_venues), s2(g.v1_residual.mean), ci(g.v1_residual.ci95), f2(g.v1_mae),
      n(g.close_n), s2(g.close_residual.mean), ci(g.close_residual.ci95), f2(g.close_mae),
      g.visitor_cover_pct == null ? '—' : f2(g.visitor_cover_pct) + '% of ' + n(g.visitor_cover_n) + ' (' + pv(g.visitor_cover_p) + ')'])));
  const sg = k => v.subgroups.find(g => g.group === k) || null;
  const all = sg('all non-neutral'), hi = sg('gain >= 3,000 ft');
  if (all && hi) {
    out.push('**Why an additive altitude term would double count.** Across all non-neutral games V1\u2019s residual is ' + s2(all.v1_residual.mean)
      + ' pts (95% CI ' + ci(all.v1_residual.ci95) + '): its 4.082-pt league home-field constant over-credits the home side on average. On 3,000+ ft visits the residual is '
      + s2(hi.v1_residual.mean) + ' (' + ci(hi.v1_residual.ci95) + '): V1 is already about right there. The regression\u2019s "altitude effect" is the gap between the two, so adding it to V1 without also recalibrating V1\u2019s home-field constant would push mountain home teams past where V1 already has them. The football-only margin calibrator (football/cfb_p4/margin_calibration.js, SHADOW) is the place that general lean is measured.');
    out.push('');
    out.push('**The closing line at altitude.** On ' + n(hi.close_n) + ' 3,000+ ft visits with a close, the home side beat the closing number by ' + s2(hi.close_residual.mean)
      + ' pts on average (95% CI ' + ci(hi.close_residual.ci95) + ', venue-cluster bootstrap over ' + n(hi.host_venues) + ' venues), and visitors covered '
      + f2(hi.visitor_cover_pct) + '% of ' + n(hi.visitor_cover_n) + ' decided games (p = ' + pv(hi.visitor_cover_p) + ' against 50%). '
      + 'With only ' + n(hi.host_venues) + ' venues the interval is fragile, the cover rate is not distinguishable from a coin flip, and the research package\u2019s fixed-effects ATS estimate was not significant either. It is a monitoring item, not an edge.');
    out.push('');
  }
  out.push('The 6x ratio rows are descriptive: most "6x" trips gain under 1,000 ft (sea-level visitors to modest venues), so the ratio mostly flags trips that are not altitude at all.');
  const nominal = v.subgroups.filter(g => g.visitor_cover_p != null && g.visitor_cover_p < 0.05 && g.group !== 'all non-neutral');
  out.push('');
  out.push('**Multiple comparisons.** ' + (v.subgroups.length - 1) + ' subgroups are shown; at p < 0.05 roughly one would clear by chance alone. '
    + (nominal.length ? nominal.length + ' did on cover rate (' + nominal.map(g => '"' + g.group + '", n ' + n(g.visitor_cover_n) + ', p ' + pv(g.visitor_cover_p)).join('; ')
      + '). Each is post hoc and none was a pre-registered candidate, so none is a finding.' : 'None did on cover rate.'));
  out.push('');

  out.push('## Placebos and holdouts');
  out.push('');
  const pp = v.placebo.permutation;
  out.push('- **Permutation (within season, ' + n(pp.shuffles) + ' shuffles):** observed all-games improvement ' + s3(pp.observed)
    + '; shuffled 5/50/95% quantiles ' + (pp.null_q || []).map(s3).join(' / ') + '; p = ' + pv(pp.p) + '.');
  const d = v.placebo.descent;
  if (d) out.push('- **Descent placebo:** visitors playing 1,000+ ft below normal: ' + s2(d.ols) + ' (SE ' + f2(d.se) + ', 95% CI ' + ci(d.ci95)
    + ', ' + n(d.support_games) + ' games). Altitude physiology predicts zero; a positive value points at travel or region rather than altitude.');
  out.push('');
  out.push('Leave-one-mountain-venue-out (fit without the venue, predict its games):');
  out.push('');
  out.push(table(['venue', 'elev ft', '3,000+ visits', 'coef without it', 'MAE before', 'MAE after'],
    v.venue_holdouts.leave_one_out.map(l => [l.venue, n(l.elev_ft), n(l.high_gain_games), s2(l.coef_without), f3(l.holdout_mae_before), f3(l.holdout_mae_after)])));
  const ph = v.venue_holdouts.pooled;
  if (ph) out.push('Pooled over held-out venues: MAE ' + f3(ph.mae_before) + ' → ' + f3(ph.mae_after) + ' on ' + n(ph.n) + ' games.');
  out.push('');

  out.push('## Gates');
  out.push('');
  out.push(table(['gate', 'result', 'evidence'], v.gates.map(g => ['`' + g.id + '`', yes(g.pass), '`' + JSON.stringify(g.evidence).replace(/\|/g, '/').slice(0, 220) + '`'])));
  out.push('');
  out.push('## Gaps');
  out.push('');
  out.push('- No per-quote timestamps exist in the line archive: "close" is the archive’s final consensus number, not a verified kickoff-minute quote, and there is no pre-2013 opener for most games.');
  out.push('- Historic stadiums the public provider no longer lists (Hughes, Sam Boyd, Aloha, Qualcomm …) take their elevation from the research package’s CollegeFootballData capture at MEDIUM confidence; the USGS service could not be reached to re-verify them.');
  out.push('- Neutral-site games are described but not modelled: the adjustment was fitted on true home games only.');
  out.push('- Play-level interactions (defensive play load, opponent pace) can only be measured through 2021 and have no live pregame input, so they cannot price even if real.');
  out.push('- The baseline replay carries no quarterback, injury or weather inputs (none exist historically), which is how V1 is replayed everywhere in this repository.');
  out.push('');
  return out.join('\n') + '\n';
}

module.exports = { render };
