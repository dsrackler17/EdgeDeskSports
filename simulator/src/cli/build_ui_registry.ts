/* Write lib/edgedesk_simulator_sports.js — the sport registry the reader shows
   (status, blockers, known limitations, tabs: public, never a probability) —
   from simulator/src/sports/registry.ts, so the page and the gate that decides
   publication can never disagree.
     node simulator/src/cli/build_ui_registry.ts [--check] */
import fs from 'node:fs';
import path from 'node:path';
import { REPO } from '../sports/nfl/model_adapter.ts';
import { sportRegistry } from '../sports/registry.ts';
import { NFL_2026 } from '../sports/nfl/config.ts';

const OUT = path.join(REPO, 'lib', 'edgedesk_simulator_sports.js');
export function uiRegistrySource(): string {
  const data = {
    schema: 'edgedesk_sim_sports_v1',
    sports: sportRegistry().map((s) => ({ key: s.key, label: s.label, status: s.status, structure: s.structure, tabs: s.tabs, blockers: s.blockers, limitations: s.limitations, activation_path: s.activation_path })),
    nfl: { season: String(NFL_2026.season), competition: NFL_2026.competition, rules_version: NFL_2026.rules_version,
      estimated_inputs: ['Postseason rest (from the format)', 'Super Bowl venue and designated home', 'Scores for points-ranking tiebreaks (linemaker team-points model)'] }
  };
  return `/* GENERATED by simulator/src/cli/build_ui_registry.ts from simulator/src/sports/registry.ts — do not edit by hand.
   The Simulator's sport registry for the reader: statuses, exact blockers and known
   limitations. Public metadata only; no simulated number is ever in this file. */
(function (root) {
  var D = ${JSON.stringify(data, null, 1)};
  if (typeof module === 'object' && module.exports) module.exports = D;
  if (root) root.EDSimSports = D;
})(typeof self !== 'undefined' ? self : (typeof globalThis !== 'undefined' ? globalThis : this));
`;
}
const src = uiRegistrySource();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== src) { console.error('lib/edgedesk_simulator_sports.js is stale: run node simulator/src/cli/build_ui_registry.ts'); process.exit(1); }
  console.log('lib/edgedesk_simulator_sports.js is current');
} else { fs.writeFileSync(OUT, src); console.log('wrote lib/edgedesk_simulator_sports.js'); }
