/* Write lib/edgedesk_simulator_sports.js — the sport registry the reader shows
   (status, blockers, known limitations, tabs: public, never a probability) —
   from simulator/src/sports/registry.ts, so the page and the gate that decides
   publication can never disagree.
     node simulator/src/cli/build_ui_registry.ts [--check] */
import fs from 'node:fs';
import path from 'node:path';
import { REPO } from '../sports/nfl/model_adapter.ts';
import { sportRegistry } from '../sports/registry.ts';
import { NFL_2026 } from '../sports/nfl/config.ts';
import { NHL_2027 } from '../sports/nhl/config.ts';
import { NBA_2026_27 } from '../sports/nba/config.ts';
import { NCAAM_2027 } from '../sports/ncaam/config.ts';
import { MLB_2026 } from '../sports/mlb/config.ts';
import { WNBA_2026 } from '../sports/wnba/config.ts';
import { UFC_2026 } from '../sports/ufc/config.ts';
import { GOLF_2026 } from '../sports/golf/config.ts';
import { TENNIS_2026 } from '../sports/tennis/config.ts';
import { CBASE_2027 } from '../sports/college_baseball/config.ts';

const OUT = path.join(REPO, 'lib', 'edgedesk_simulator_sports.js');
export function uiRegistrySource(): string {
  const data = {
    schema: 'edgedesk_sim_sports_v1',
    sports: sportRegistry().map((s) => Object.assign({ key: s.key, label: s.label, status: s.status, structure: s.structure, tabs: s.tabs, blockers: s.blockers, limitations: s.limitations, activation_path: s.activation_path },
      s.games ? { games: s.games } : {})),
    nfl: { season: String(NFL_2026.season), competition: NFL_2026.competition, rules_version: NFL_2026.rules_version,
      estimated_inputs: ['Postseason rest (from the format)', 'Super Bowl venue and designated home', 'Scores for points-ranking tiebreaks (linemaker team-points model)'] },
    /* the NHL's runs are published under the season label (sim_runs.season '2026-27') */
    nhl: { season: NHL_2027.season_label, competition: NHL_2027.competition, rules_version: NHL_2027.rules_version },
    /* the NBA's too (sim_runs.season '2026-27') */
    nba: { season: NBA_2026_27.label, competition: NBA_2026_27.competition, rules_version: NBA_2026_27.rules_version },
    mlb: { season: String(MLB_2026.season), competition: MLB_2026.competition, rules_version: MLB_2026.rules_version },
    wnba: { season: WNBA_2026.label, competition: WNBA_2026.competition, rules_version: WNBA_2026.rules_version },
    ufc: { season: UFC_2026.label, competition: UFC_2026.competition, rules_version: UFC_2026.rules_version, horizon_days: UFC_2026.horizon_days },
    /* golf publishes one competition per tour event (<tour>-<ESPN event id>): the reader lists them */
    golf: { season: GOLF_2026.label, competition: 'one per tour event', rules_version: GOLF_2026.rules_version, tours: GOLF_2026.tours },
    /* tennis publishes one competition per singles main draw (<tour>-<ESPN tournament id>) and one for the day's matches ("matches") */
    tennis: { season: TENNIS_2026.label, competition: 'one per draw, and matches', rules_version: TENNIS_2026.rules_version },
    college_baseball: { season: CBASE_2027.label, competition: CBASE_2027.competition, rules_version: CBASE_2027.rules_version, regionals_start: CBASE_2027.regionals_start },
    ncaam: { season: String(NCAAM_2027.season), competition: NCAAM_2027.competition, rules_version: NCAAM_2027.rules_version,
      pre_selection: NCAAM_2027.pre_selection, conference_tournaments: NCAAM_2027.conference_tournaments, venue: NCAAM_2027.venue,
      live: (() => { const l = JSON.parse(fs.readFileSync(path.join(REPO, 'basketball', 'ncaam_forecast', 'config', 'live.json'), 'utf8')); return { enabled: l.enabled === true, blockers: l.blockers }; })() },
    /* women's college basketball: the pregame forecasts only (basketball/ncaaw_forecast); no tournament simulation and no live writer exist */
    ncaaw: { season: '2027',
      pre_selection: { enabled: false, reason: 'No women\'s tournament simulation is built.' },
      conference_tournaments: { enabled: false, reason: 'No women\'s tournament simulation is built.' },
      live: { enabled: false, blockers: ['Not built for the women\'s game: no live writer and no women\'s live feed (the games slate carries no women\'s games); the database refuses live rows while ncaaw_fc_config.live_enabled is not \'true\'.'] } }
  };
  return `/* GENERATED by simulator/src/cli/build_ui_registry.ts from simulator/src/sports/registry.ts — do not edit by hand.
   The Simulator's sport registry for the reader: statuses, exact blockers and known
   limitations. Public metadata only; no simulated number is ever in this file. */
(function (root) {
  var D = ${JSON.stringify(data, null, 1)};
  if (typeof module === 'object' && module.exports) module.exports = D;
  if (root) root.EDSimSports = D;
})(typeof self !== 'undefined' ? self : (typeof globalThis !== 'undefined' ? globalThis : this));
`;
}
const src = uiRegistrySource();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== src) { console.error('lib/edgedesk_simulator_sports.js is stale: run node simulator/src/cli/build_ui_registry.ts'); process.exit(1); }
  console.log('lib/edgedesk_simulator_sports.js is current');
} else { fs.writeFileSync(OUT, src); console.log('wrote lib/edgedesk_simulator_sports.js'); }
