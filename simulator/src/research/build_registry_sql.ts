/* ===========================================================================
   Generate supabase/simulator_registry.sql from simulator/research/registration.json.

   The research registry (public.research_models, public.research_model_versions,
   research_model_current) is deployed-only: its columns are not in this
   repository. Like supabase/nba_roster_adjusted_registry.sql (whose helpers
   this copies), the generated file reads the live columns and writes the
   registration into whatever form they take, refusing by name a required
   column it has nothing for. It registers; it never promotes and never writes
   a result row.
     node simulator/src/research/build_registry_sql.ts           (writes)
     node simulator/src/research/build_registry_sql.ts --check   (exit 1 if stale)
   =========================================================================== */
import fs from 'node:fs';
import path from 'node:path';
import { REPO } from '../sports/nfl/model_adapter.ts';
import { canonicalJson, sha256Hex } from '../core/canonical.ts';

const SRC = path.join(REPO, 'simulator', 'research', 'registration.json');
const OUT = path.join(REPO, 'supabase', 'simulator_registry.sql');

/* what differs between registrations; the NFL values reproduce the original file byte for byte */
export interface RegistryTarget { src: string; sport: string; sportKey: string; family: string; configTable: string; configPrefix: string; requires: string; registration: string; configNote: string; header: string; generator: string }
export const NFL_TARGET: RegistryTarget = { src: SRC, sport: 'NFL', sportKey: 'americanfootball_nfl', family: 'season_simulator', configTable: 'public.sim_config', configPrefix: '',
  requires: 'supabase/simulator.sql', registration: 'simulator/research/registration.json', configNote: 'research_models key of the NFL season simulator', header: '', generator: 'simulator/src/research/build_registry_sql.ts' };

export function generate(target: RegistryTarget = NFL_TARGET): string {
  const out = generateRaw(target);
  if (target === NFL_TARGET) return out;
  return out
    .split("jsonb_build_object(c, 'NFL')").join("jsonb_build_object(c, '" + target.sport + "')")
    .split("jsonb_build_object(c, 'americanfootball_nfl')").join("jsonb_build_object(c, '" + target.sportKey + "')")
    .split("jsonb_build_object(c, 'season_simulator')").join("jsonb_build_object(c, '" + target.family + "')")
    .split('public.sim_config').join(target.configTable)
    .split("'research_model_key'").join("'" + target.configPrefix + "research_model_key'")
    .split("'research_model_version'").join("'" + target.configPrefix + "research_model_version'")
    .split("'research_model_version_ref'").join("'" + target.configPrefix + "research_model_version_ref'")
    .split("'registration_sha256'").join("'" + target.configPrefix + "registration_sha256'")
    .split("'research_models key of the NFL season simulator'").join("'" + target.configNote + "'")
    .split('simulator/research/registration.json').join(target.registration)
    .split("then raise exception 'apply supabase/simulator.sql first'").join("then raise exception 'apply " + target.requires + " first'")
    .split('(EdgeDesk Simulator)').join('(EdgeDesk ' + target.sport + ')')
    .split("-- simulator_registry.sql — register the EdgeDesk Simulator's NFL season model").join('-- ' + target.header)
    .split('-- REQUIRES supabase/simulator.sql and the research registry.').join('-- REQUIRES ' + target.requires + ' and the research registry.')
    .split('GENERATED by simulator/src/research/build_registry_sql.ts from').join('GENERATED by ' + target.generator + ' from');
}

function generateRaw(target: RegistryTarget): string {
  const reg = JSON.parse(fs.readFileSync(target.src, 'utf8'));
  delete reg.content_sha256;
  const sha = sha256Hex(canonicalJson(reg));
  const S = JSON.stringify({ ...reg, content_sha256: sha });
  if (S.includes('$simreg$')) throw new Error('the registration contains the dollar-quote tag');
  return `-- =============================================================================
-- simulator_registry.sql — register the EdgeDesk Simulator's NFL season model
-- (${reg.model_key} v${reg.version}) as ${reg.status}, tier ${reg.provenance}, in the research
-- registry, BEFORE any holdout evaluation. docs/simulator/README.md.
--
-- GENERATED by simulator/src/research/build_registry_sql.ts from
-- simulator/research/registration.json (content sha256
-- ${sha}). Do not edit by hand.
--
-- WHAT IT DOES. One research_models row (EXPERIMENTAL, T3) and one
-- research_model_versions row (version ${reg.version}, EXPERIMENTAL) carrying the
-- objective, the windows, the minimum sample, the primary metric, the
-- promotion criteria C1-C4 written before validation, the forking-paths
-- disclosure and the specification, in whatever form the live columns take.
-- Then the version row is named in public.sim_config.
--
-- WHAT IT DOES NOT DO. No research_model_results row (there is no result, so
-- every reader shows Experimental). No promotion. No change to a registered row.
--
-- REQUIRES supabase/simulator.sql and the research registry.
-- CONVENTION (supabase/README.md): idempotent, additive, pasted into the SQL
-- editor, no psql meta-commands, ends in a report. Safe to run again.
-- =============================================================================

do $req$ begin
  if to_regclass('public.research_models') is null or to_regclass('public.research_model_versions') is null then
    raise exception 'the research registry (public.research_models, public.research_model_versions) is not in this database: nothing was registered';
  end if;
  if to_regclass('public.sim_config') is null then raise exception 'apply supabase/simulator.sql first'; end if;
end $req$;

-- helpers for this session only (pg_temp: gone when the editor's session ends)
create or replace function pg_temp.edr_has(p_rel regclass, p_names text[]) returns text
language sql stable as $f$
  select u.n from unnest(p_names) with ordinality u(n, i)
   where exists (select 1 from pg_attribute a where a.attrelid = p_rel and a.attname = u.n and a.attnum > 0 and not a.attisdropped)
   order by u.i limit 1
$f$;
create or replace function pg_temp.edr_typ(p_rel regclass, p_col text) returns text
language sql stable as $f$
  select format_type(a.atttypid, a.atttypmod) from pg_attribute a where a.attrelid = p_rel and a.attname = p_col and a.attnum > 0 and not a.attisdropped
$f$;
create or replace function pg_temp.edr_label(p_rel regclass, p_col text, p_wanted text[]) returns text
language plpgsql stable as $f$
declare t oid; l text;
begin
  select a.atttypid into t from pg_attribute a where a.attrelid = p_rel and a.attname = p_col and a.attnum > 0;
  if exists (select 1 from pg_type where oid = t and typtype = 'e') then
    select e.enumlabel into l from pg_enum e where e.enumtypid = t and lower(e.enumlabel) = any (p_wanted)
     order by array_position(p_wanted, lower(e.enumlabel)) limit 1;
    if l is null then
      raise exception 'research registry: %.% is an enum with no label for % (its labels: %) — nothing was registered', p_rel, p_col, p_wanted[1],
        (select string_agg(enumlabel, ', ' order by enumsortorder) from pg_enum where enumtypid = t);
    end if;
    return l;
  end if;
  return p_wanted[1];
end $f$;
create or replace function pg_temp.edr_val(p_rel regclass, p_col text, p_text text, p_json jsonb, p_range jsonb) returns jsonb
language plpgsql stable as $f$
declare t text := pg_temp.edr_typ(p_rel, p_col);
begin
  if t is null then return null; end if;
  if t like '%range' then return case when p_range is null or jsonb_typeof(p_range) <> 'array' then 'null'::jsonb
    else to_jsonb('[' || (p_range ->> 0) || ',' || (p_range ->> 1) || ')') end; end if;
  if t = 'date' then return case when p_range is null or jsonb_typeof(p_range) <> 'array' then 'null'::jsonb else p_range -> 0 end; end if;
  if t in ('jsonb', 'json') then return coalesce(p_json, to_jsonb(p_text)); end if;
  if t in ('integer', 'bigint', 'smallint', 'numeric') then return case when jsonb_typeof(p_json) = 'number' then p_json else 'null'::jsonb end; end if;
  if t = 'boolean' then return case when jsonb_typeof(p_json) = 'boolean' then p_json else 'null'::jsonb end; end if;
  return to_jsonb(coalesce(p_text, p_json #>> '{}', p_json::text));
end $f$;
create or replace function pg_temp.edr_insert(p_rel regclass, p_vals jsonb, p_ret text) returns text
language plpgsql as $f$
declare cols text; missing text; out_ text;
begin
  select string_agg(quote_ident(k), ', ') into cols from jsonb_object_keys(p_vals) k;
  select string_agg(a.attname::text, ', ') into missing from pg_attribute a
   where a.attrelid = p_rel and a.attnum > 0 and not a.attisdropped and a.attnotnull and not a.atthasdef
     and a.attidentity = '' and a.attgenerated = '' and not (p_vals ? a.attname::text);
  if missing is not null then
    raise exception 'research registry: % requires % and this file has nothing to put there — nothing was registered (map it in simulator/src/research/build_registry_sql.ts)', p_rel, missing;
  end if;
  execute format('insert into %s (%s) select %s from jsonb_populate_record(null::%s, $1) returning %I::text', p_rel, cols, cols, p_rel, p_ret) into out_ using p_vals;
  return out_;
end $f$;

begin;

do $reg$
declare
  S jsonb := $simreg$${S}$simreg$::jsonb;
  m regclass := 'public.research_models';
  v regclass := 'public.research_model_versions';
  mv jsonb; vv jsonb; mach jsonb := S -> 'machine';
  kcol text; ncol text; refcol text; fkcol text; vcol text; vid text; c text; ref text; vref text; have boolean;
  pairs text[][] := array[
    array['training_window', 'train_window', 'training_period', 'training'],
    array['validation_window', 'valid_window', 'validation_period', 'validation'],
    array['holdout_window', 'holdout_period', 'holdout', 'test_window']];
  wkeys text[] := array['training', 'validation', 'holdout'];
  i int;
begin
  kcol := pg_temp.edr_has(m, array['model_key', 'key', 'model_name', 'model', 'slug', 'code', 'name']);
  if kcol is null then raise exception 'research registry: research_models has no key column — nothing was registered'; end if;
  select a.attname::text, ra.attname::text into fkcol, refcol
    from pg_constraint k
    join pg_attribute a on a.attrelid = k.conrelid and a.attnum = k.conkey[1]
    join pg_attribute ra on ra.attrelid = k.confrelid and ra.attnum = k.confkey[1]
   where k.contype = 'f' and k.conrelid = v and k.confrelid = m limit 1;
  if fkcol is null then
    fkcol := pg_temp.edr_has(v, array['model_key', 'model_id', 'research_model_id', 'model']);
    refcol := case when fkcol in ('model_id', 'research_model_id') then pg_temp.edr_has(m, array['id', 'model_id']) else kcol end;
  end if;
  if fkcol is null or refcol is null then raise exception 'research registry: cannot tell how research_model_versions points at research_models — nothing was registered'; end if;
  vcol := pg_temp.edr_has(v, array['version', 'model_version', 'version_label', 'semver', 'label']);
  vid := pg_temp.edr_has(v, array['id', 'version_id', 'model_version_id']);

  execute format('select %I::text from %s where %I::text = $1 limit 1', refcol, m, kcol) into ref using S ->> 'model_key';
  if ref is null then
    mv := jsonb_build_object(kcol, S ->> 'model_key');
    ncol := pg_temp.edr_has(m, array['name', 'title', 'display_name', 'label']);
    if ncol is not null and ncol <> kcol then mv := mv || jsonb_build_object(ncol, S ->> 'name'); end if;
    c := pg_temp.edr_has(m, array['sport', 'league']); if c is not null then mv := mv || jsonb_build_object(c, 'NFL'); end if;
    c := pg_temp.edr_has(m, array['sport_key']); if c is not null then mv := mv || jsonb_build_object(c, 'americanfootball_nfl'); end if;
    c := pg_temp.edr_has(m, array['status', 'model_status', 'maturity']); if c is not null then mv := mv || jsonb_build_object(c, pg_temp.edr_label(m, c, array['experimental'])); end if;
    c := pg_temp.edr_has(m, array['provenance', 'evidence_provenance', 'tier', 'evidence_tier']);
    if c is not null then mv := mv || jsonb_build_object(c, pg_temp.edr_label(m, c, array['t3', 'research_model', 'research', 'model'])); end if;
    c := pg_temp.edr_has(m, array['objective', 'goal']); if c is not null then mv := mv || jsonb_build_object(c, S ->> 'objective'); end if;
    c := pg_temp.edr_has(m, array['hypothesis']); if c is not null then mv := mv || jsonb_build_object(c, S ->> 'hypothesis'); end if;
    c := pg_temp.edr_has(m, array['description', 'summary']); if c is not null then mv := mv || jsonb_build_object(c, S ->> 'hypothesis'); end if;
    c := pg_temp.edr_has(m, array['family', 'category', 'module', 'domain']); if c is not null then mv := mv || jsonb_build_object(c, 'season_simulator'); end if;
    c := pg_temp.edr_has(m, array['owner', 'created_by', 'registered_by']); if c is not null then mv := mv || jsonb_build_object(c, (S ->> 'registered_at') || ' preregistration (EdgeDesk Simulator)'); end if;
    c := pg_temp.edr_has(m, array['metadata', 'meta', 'spec', 'details', 'config']);
    if c is not null then mv := mv || jsonb_build_object(c, pg_temp.edr_val(m, c, null, S, null)); end if;
    ref := pg_temp.edr_insert(m, mv, refcol);
    raise notice 'research registry: % registered', S ->> 'model_key';
  else
    raise notice 'research registry: % was already registered and is left as it is', S ->> 'model_key';
  end if;

  if vcol is not null then
    execute format('select exists (select 1 from %s where %I::text = $1 and %I::text = $2)', v, fkcol, vcol) into have using ref, S ->> 'version';
  else
    execute format('select exists (select 1 from %s where %I::text = $1)', v, fkcol) into have using ref;
  end if;
  if not have then
    vv := jsonb_build_object(fkcol, ref);
    if vcol is not null then vv := vv || jsonb_build_object(vcol, S ->> 'version'); end if;
    c := pg_temp.edr_has(v, array['status', 'model_status', 'maturity']); if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_label(v, c, array['experimental'])); end if;
    c := pg_temp.edr_has(v, array['provenance', 'evidence_provenance', 'tier']); if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_label(v, c, array['t3', 'research_model', 'research', 'model'])); end if;
    for i in 1 .. 3 loop
      c := pg_temp.edr_has(v, pairs[i:i][1:4]::text[]);
      if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, S ->> (wkeys[i] || '_window'),
        jsonb_build_object('from', mach -> 'window_dates' -> wkeys[i] -> 0, 'to', mach -> 'window_dates' -> wkeys[i] -> 1, 'description', S ->> (wkeys[i] || '_window')),
        mach -> 'window_dates' -> wkeys[i])); end if;
    end loop;
    c := pg_temp.edr_has(v, array['objective', 'goal']); if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, S ->> 'objective', null, null)); end if;
    c := pg_temp.edr_has(v, array['hypothesis']); if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, S ->> 'hypothesis', null, null)); end if;
    c := pg_temp.edr_has(v, array['min_sample', 'minimum_sample', 'min_n', 'sample_target']);
    if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, (S -> 'minimum_sample')::text,
      case when pg_temp.edr_typ(v, c) in ('jsonb', 'json') then S -> 'minimum_sample' else mach -> 'minimum_sample' end, null)); end if;
    c := pg_temp.edr_has(v, array['success_metric', 'primary_metric', 'metric']); if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, S ->> 'primary_metric', null, null)); end if;
    c := pg_temp.edr_has(v, array['promotion_criteria', 'decision_rule', 'criteria', 'success_criteria']);
    if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, S -> 'promotion_criteria' ->> 'decision_rule', S -> 'promotion_criteria', null)); end if;
    c := pg_temp.edr_has(v, array['forking_paths', 'forking_paths_disclosure', 'disclosure', 'garden_of_forking_paths']);
    if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, null, S -> 'forking_paths', null)); end if;
    c := pg_temp.edr_has(v, array['spec', 'metadata', 'meta', 'params', 'config', 'details', 'definition', 'protocol']);
    if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, null, S -> 'spec' || jsonb_build_object('content_sha256', S ->> 'content_sha256', 'registration', 'simulator/research/registration.json'), null)); end if;
    c := pg_temp.edr_has(v, array['notes', 'description']);
    if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c,
      'Preregistered ' || (S ->> 'registered_at') || ': simulator/research/registration.json sha256 ' || (S ->> 'content_sha256') || '. No result until a validation report writes one.', null, null)); end if;
    perform pg_temp.edr_insert(v, vv, fkcol);
  end if;

  if vid is not null and vcol is not null then
    execute format('select %I::text from %s where %I::text = $1 and %I::text = $2 limit 1', vid, v, fkcol, vcol) into vref using ref, S ->> 'version';
  end if;
  vref := coalesce(vref, ref || ':' || (S ->> 'version'));
  insert into public.sim_config (key, value, note) values
    ('research_model_key', S ->> 'model_key', 'research_models key of the NFL season simulator'),
    ('research_model_version', S ->> 'version', 'the registered version the simulator runs as'),
    ('research_model_version_ref', vref, 'research_model_versions row (as text)'),
    ('registration_sha256', S ->> 'content_sha256', 'simulator/research/registration.json')
  on conflict (key) do update set value = excluded.value, updated_at = now();
end $reg$;

commit;

-- THE REPORT: the model as research_model_current reads it. Every row should say ok.
create or replace function pg_temp.edr_report() returns table (piece text, state text)
language plpgsql as $f$
declare j jsonb; s text; p text;
begin
  if to_regclass('public.research_model_current') is not null then
    execute 'select to_jsonb(r) from public.research_model_current r where lower(coalesce(to_jsonb(r) ->> ''model_key'', to_jsonb(r) ->> ''key'', to_jsonb(r) ->> ''model_name'', to_jsonb(r) ->> ''model'', to_jsonb(r) ->> ''name'')) = lower($1) limit 1'
      into j using '${reg.model_key}';
  end if;
  s := lower(coalesce(j ->> 'status', j ->> 'model_status', j ->> 'maturity', ''));
  p := coalesce(j ->> 'passed', 'null');
  piece := '1 ${reg.model_key} is EXPERIMENTAL with no result';
  state := case when to_regclass('public.research_model_current') is null then 'CHECK THIS: research_model_current is not in this database'
                when j is null then 'CHECK THIS: not in research_model_current'
                when s <> 'experimental' then 'CHECK THIS: status reads ' || s
                when p = 'true' then 'CHECK THIS: a result row shows passed = true'
                else 'ok' end;
  return next;
  piece := '2 the simulator names version ${reg.version} and its registry row';
  state := case when (select value from public.sim_config where key = 'research_model_version') = '${reg.version}'
                 and (select value from public.sim_config where key = 'research_model_version_ref') is not null then 'ok' else 'CHECK THIS' end;
  return next;
end $f$;
select * from pg_temp.edr_report();
`;
}

const isMain = !!process.argv[1] && path.resolve(process.argv[1]).endsWith(path.join('research', 'build_registry_sql.ts'));
const check = process.argv.includes('--check');
const sql = isMain ? generate() : '';
if (!isMain) { /* imported by another generator */ }
else if (check) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== sql) { console.error('supabase/simulator_registry.sql is stale: run node simulator/src/research/build_registry_sql.ts'); process.exit(1); }
  console.log('supabase/simulator_registry.sql is current');
} else {
  fs.writeFileSync(OUT, sql);
  console.log('wrote supabase/simulator_registry.sql');
}
