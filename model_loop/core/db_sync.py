"""SQL that mirrors the model loop's committed records into Supabase.

  python3 -m model_loop.core.db_sync snapshots <ledger.jsonl> > snapshots.sql
  python3 -m model_loop.core.db_sync registry <sport>        > registry.sql

The committed files stay the source of truth. Both outputs are idempotent:
snapshots go through public.model_rating_snapshots_ingest (rows already
present are skipped) and the registry writer leaves any version it already
holds untouched. Each file is a no-op with a notice when its target is not
installed yet (supabase/model_loop.sql, the research registry).
"""
import json
import os
import sys

from .registry_sql import emit

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def snapshots_sql(ledger_path, chunk=500):
    rows = [json.loads(l) for l in open(ledger_path) if l.strip()]
    out = ["-- generated by model_loop/core/db_sync.py from " + os.path.relpath(ledger_path, ROOT)]
    for i in range(0, len(rows), chunk):
        blob = json.dumps(rows[i:i + chunk], sort_keys=True)
        if "$mls$" in blob:
            raise ValueError("payload contains the dollar-quote tag")
        out.append("do $do$ begin\n"
                   "  if to_regprocedure('public.model_rating_snapshots_ingest(jsonb)') is null then\n"
                   "    raise notice 'model_rating_snapshots is not installed (supabase/model_loop.sql): skipped';\n"
                   "  else\n"
                   f"    raise notice 'model_rating_snapshots: % new row(s)', public.model_rating_snapshots_ingest($mls${blob}$mls$::jsonb);\n"
                   "  end if;\nend $do$;")
    return "\n".join(out) + "\n"


def registry_sql(sport):
    """Every version in docs/model-loop/<sport>/versions.json, each with its
    evidence as the result row. Versions are written EXPERIMENTAL: none has
    beaten the closing line, and VALIDATED is a person's call."""
    path = os.path.join(ROOT, "docs", "model-loop", sport.lower(), "versions.json")
    doc = json.load(open(path))
    versions = []
    for v in doc["versions"]:
        served = v["version"] == doc["current"]
        ev = v.get("evidence") or {}
        weekly = v.get("promoted_by") == "weekly-loop"
        prereg = v.get("promoted_by") == "preregistered-rule"
        clv = v.get("promoted_by") == "clv-programme"
        versions.append({
            "version": v["version"], "training": {"seasons": "walk-forward, every season before the one priced"},
            "training_text": "walk-forward: every coefficient fitted only on earlier seasons",
            "validation_text": "full backtest from 2011 through the season of promotion",
            "holdout_text": "the most recent full season at promotion",
            "spec": {"config": v["config"], "config_sha256": v["config_sha256"], "parent": v.get("parent"),
                     "promoted_by": v.get("promoted_by"), "promoted_at": v.get("promoted_at"), "served_now": served},
            "notes": (("SERVED. " if served else "") + v.get("reason", ""))[:2000],
            "result": {"passed": bool(weekly or prereg or clv), "note": ("cleared the weekly loop's full-backtest rule" if weekly else
                                                                  "cleared the preregistered rule against the incumbent" if prereg else
                                                                  "passed its pre-registered CLV holdout gate; tracked live, never served" if clv else
                                                                  "served by owner decision; did not clear the preregistered holdout rule"),
                       "evidence": ev, "holdout": ev.get("recent_season") or ev.get("holdout_2025") or {}}})
    payload = {"model_key": f"{doc['sport']}-CORE", "title": f"{doc['sport']} core projection (model loop)", "sport": doc["sport"],
               "objective": "Lower margin error and log loss than the served version, measured against the closing line, every week.",
               "primary_metric": "margin MAE vs result and win-probability log loss, closing line as baseline",
               "decision_rule": "Weekly loop: promote only if full-backtest MAE and log loss both improve by the noise floor and the most recent full season is no worse.",
               "forking_paths": {"candidates_log": f"docs/model-loop/{sport.lower()}/candidates.jsonl"},
               "generated_at": doc["versions"][-1].get("promoted_at"), "versions": versions}
    return emit(payload, f"model loop registry sync for {doc['sport']}: every version in docs/model-loop/{sport.lower()}/versions.json")


def main(argv=None):
    a = argv or sys.argv[1:]
    if not a or a[0] not in ("snapshots", "registry"):
        print(__doc__)
        sys.exit(2)
    sys.stdout.write(snapshots_sql(a[1]) if a[0] == "snapshots" else registry_sql(a[1]))


if __name__ == "__main__":
    main()
