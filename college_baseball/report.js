'use strict';
/* ===========================================================================
   EdgeDesk college baseball — the delivery report (Phase 17), generated.

     node college_baseball/report.js        -> docs/college-baseball/REPORT.md

   Every number in the report is read from a committed evidence file at the
   moment it is written; nothing is typed by hand, so the report cannot drift
   from the evidence. A file that has not been produced yet is reported as
   "not run", never estimated. The prose around the numbers is fixed and
   states only what the numbers decide.
   =========================================================================== */
const fs = require('fs');
const path = require('path');
const C = require('./config');
const REG = require('./lib/registry');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'docs', 'college-baseball', 'REPORT.md');
const VAL = C.PATHS.validation;
function read(f) { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch (_) { return null; } }
const f4 = (v) => (v == null ? '—' : Number(v).toFixed(4));
const f5 = (v) => (v == null ? '—' : Number(v).toFixed(5));
const pct = (v) => (v == null ? '—' : (100 * v).toFixed(1) + '%');
const int = (v) => (v == null ? '—' : Number(v).toLocaleString('en-US'));
const ci = (c) => (c && c.ci95 ? `${c.mean_diff >= 0 ? '+' : ''}${Number(c.mean_diff).toFixed(4)} (95% ${Number(c.ci95[0]).toFixed(4)} to ${Number(c.ci95[1]).toFixed(4)})` : '—');
const verdict = (c) => (!c ? '—' : c.a_better ? 'better' : c.b_better ? 'worse' : 'not distinguishable');
function table(head, rows) { return ['| ' + head.join(' | ') + ' |', '|' + head.map(() => '---').join('|') + '|'].concat(rows.map((r) => '| ' + r.join(' | ') + ' |')).join('\n'); }

const DESCR = {
  home_rate: 'home win rate (constant)', elo: 'Elo, margin-free, tuned K / home / carryover', pythag: 'Pythagenpat with a prior', massey: 'Massey (ridge on run margin)', bt: 'Bradley-Terry (ridge logistic)',
  poisson_flat: 'Poisson attack/defence, flat shrinkage', hier: 'hierarchical quasi-Poisson (team ⊂ conference ⊂ division), parks, carryover, uncertainty',
  hier_rest_cal: 'hier + rest layer + run-space calibration', ens: 'stacked ensemble (hier_cal, elo_cal, massey_cal, pythag_cal), made coherent in run space',
};
function describe(n) { if (DESCR[n]) return DESCR[n]; if (n.endsWith('_cal')) return (DESCR[n.slice(0, -4)] || n.slice(0, -4)) + ' + calibration fitted on the 3 prior seasons'; return n; }

function build() {
  const wf = read(C.PATHS.walkforward); const pw = read(C.PATHS.pitcherEval); const dist = read(C.PATHS.distEval); const sim = read(C.PATHS.simEval);
  const ml = read(path.join(VAL, 'ml_ensemble.json')); const fr = read(path.join(VAL, 'feature_research.json')); const abl = read(path.join(VAL, 'ablations.json'));
  const cov = read(C.PATHS.coverage); const dq = read(path.join(VAL, 'data_quality.json')); const rules = read(path.join(VAL, 'rules_evidence.json'));
  const audit = read(C.PATHS.audit); const gates = read(C.PATHS.gates); const prod = read(C.PATHS.production); const tests = read(path.join(VAL, 'test_results.json'));
  const idx = read(path.join(__dirname, 'board', 'index.json')); const tuning = read(path.join(C.PATHS.params, 'team_tuning.json'));
  const reg = REG.latest(); const chain = REG.verify();
  const L = [];
  const p = (s) => L.push(s === undefined ? '' : s);

  p('# EdgeDesk college baseball — delivery report');
  p();
  p(`Generated by \`node college_baseball/report.js\` from the committed evidence files (model version \`${C.MODEL_VERSION}\`). Do not edit by hand: re-run the generator. Every evaluation here is a **RETROSPECTIVE** reconstruction from final data (research/PROTOCOL.md §1); none is a live record, and none is a test against a betting market.`);
  p();
  p('**Research, not picks.** No price in this engine is a recommendation. No betting opportunity is shown anywhere, because no authorised college-baseball market feed exists and the release gates do not pass.');
  p();

  /* ---------------------------------------------------------------- 1 verdict */
  p('## 1. Verdict');
  p();
  const pricing = wf ? (wf.pricing ? wf.pricing.model : wf.selection.chosen) : null;
  const hold = wf && wf.windows_report && wf.windows_report.HOLDOUT;
  p(`- **Release:** ${gates ? gates.summary : 'release gates not run'}`);
  p(`- **Adversarial audit:** ${audit ? audit.summary : 'not run'}${prod ? ` Production record: ${prod.model_version}, ${prod.action || 'PROMOTED'} ${String(prod.at || '').slice(0, 10)} (evidence ${String(prod.evidence_sha256 || '').slice(0, 12)}).` : ''}`);
  if (wf) {
    p(`- **Team model chosen on SELECTION:** \`${wf.selection.chosen}\` (${describe(wf.selection.chosen)}). Best baseline: \`${wf.selection.best_baseline}\`.`);
    if (wf.pricing) p(`- **Pricing model:** \`${pricing}\` — ${wf.pricing.ensemble_adopted ? 'the ensemble beat the chosen single model on VALIDATION with a 95% interval below zero, so it prices' : 'the ensemble did not clear the adoption rule, so the chosen single model prices'}.`);
    if (hold && !hold.withheld) p(`- **HOLDOUT ${hold.seasons.join('–')}** (looked at once for this version): \`${pricing}\` log loss ${f5(hold.models[pricing].log_loss)} on ${int(hold.n)} games; vs the best baseline ${ci(wf.comparisons.HOLDOUT.pricing_vs_best_baseline)} → ${verdict(wf.comparisons.HOLDOUT.pricing_vs_best_baseline)}. Moneyline status: **${wf.status.moneyline.status}**${wf.status.moneyline.failed.length ? ' (' + wf.status.moneyline.failed.join('; ') + ')' : ''}.`);
    else p('- **HOLDOUT:** not yet evaluated for this model version; every price is PROVISIONAL.');
  }
  p('- **Market:** NOT_TESTED. No licensed, timestamped archive of college-baseball prices exists; EV is never computed.');
  p();

  /* ---------------------------------------------------------------- 2 state table */
  p('## 2. What is implemented, tested, provisional and blocked');
  p();
  const G = (id) => (gates ? (gates.gates.find((g) => g.id === id) || {}).status || '—' : 'not run');
  p(table(['Component', 'State', 'Evidence'], [
    ['Research workspace, protocol, hash-chained registry', 'IMPLEMENTED, TESTED', `research/, ${reg.length} experiments, chain ${chain && chain.ok ? 'verified' : 'NOT verified'}`],
    ['D-I coverage, canonical ids, reconciliation, quarantine, provenance', 'IMPLEMENTED, TESTED', 'validation/coverage.json, data_quality.json'],
    ['Rules registry with measured evidence', 'IMPLEMENTED, MEASURED', 'validation/rules_evidence.json'],
    ['Team quality, baselines, walk-forward', 'IMPLEMENTED, VALIDATED (retrospective)', 'validation/walkforward.json'],
    ['Run distribution (negative binomial)', 'IMPLEMENTED, VALIDATED (retrospective)', 'validation/run_distribution.json'],
    ['Pricing engine: closed form for full-game markets; inning simulator for the first five', 'IMPLEMENTED, VALIDATED (retrospective)', 'validation/simulator.json'],
    ['Starter / bullpen / workload engines, starter projection', 'IMPLEMENTED, TESTED; not in the price (no significant gain)', 'validation/pitcher_walkforward.json'],
    ['Offense, defence, environment features', 'TESTED; offense accepted but not wired, defence rejected, rest a challenger', 'validation/feature_research.json'],
    ['GLM, boosting, stacked ensemble', 'TESTED', 'validation/ml_ensemble.json'],
    ['Ablations', abl ? 'TESTED' : 'not run', 'validation/ablations.json'],
    ['Fair prices: moneyline, run lines, totals, team totals', 'IMPLEMENTED; PROVISIONAL', 'lib/pricing.js, board/'],
    ['First-five prices', sim && sim.decision ? (/PROVISIONAL/.test(sim.decision.first_five_engine) ? 'IMPLEMENTED; PROVISIONAL' : 'IMPLEMENTED; RESEARCH ONLY (miscalibrated)') : 'not evaluated', 'validation/simulator.json'],
    ['Settlement profiles', 'TEMPLATES, UNVERIFIED', 'lib/pricing.js SETTLEMENT_PROFILES'],
    ['Seven readiness states per game', 'IMPLEMENTED, TESTED', 'lib/readiness.js'],
    ['Batch inference (every game, failures listed)', idx ? 'IMPLEMENTED, RUN' : 'not run', 'board/index.json'],
    ['Adversarial auditor, promotion blocking', audit ? 'IMPLEMENTED, RUN' : 'not run', 'validation/audit.json, research/audit_log.jsonl'],
    ['Release gates', gates ? 'IMPLEMENTED, RUN' : 'not run', 'validation/release_gates.json'],
    ['Terminal (Research → Baseball → NCAA engine)', 'IMPLEMENTED, TESTED (Chromium, desktop and phone)', 'lib/edgedesk_cbase_ui.js'],
    ['Automation', 'IMPLEMENTED', '.github/workflows/college-baseball-research.yml'],
    ['Commercial data rights', 'BLOCKED — owner decision (gate G1: ' + G('G1') + ')', 'research/LICENSING.md'],
    ['Market comparison, CLV, EV', 'BLOCKED — no authorised feed', 'research/UNRESOLVED.md U-02'],
    ['Confirmed starters, lineups, weather as forecast', 'BLOCKED — no authorised source', 'research/UNRESOLVED.md U-06, U-11'],
  ]));
  p();

  /* ---------------------------------------------------------------- 3 data */
  p('## 3. Data');
  p();
  if (cov) {
    const t = cov.totals;
    p(`Source: ${C.SOURCE.name}. Seasons ${C.SEASONS.first}–${C.SEASONS.last}. ${int(t.scheduled)} scheduled contests, ${int(t.final_results)} final, ${int(t.quarantined)} quarantined, ${int(t.eligible_for_rating)} eligible for rating; ${int(t.verified_multi_source)} verified by more than one source file, ${int(t.single_source)} single-source. Box scores and starters: ${int(t.with_basic_box)} games (2024–2026). Play-by-play: ${int(t.with_play_by_play)}. Weather and market prices: 0 (no authorised source).`);
    p();
    p(table(['Season', 'D-I programs', 'Final', 'Quarantined', 'Play-by-play', 'Box score', 'Eligible'], cov.seasons.map((s) => [String(s.season), int(s.d1_programs), int(s.final_results), int(s.quarantined), int(s.with_play_by_play), int(s.with_basic_box), int(s.eligible_for_rating)])));
    p();
    p('Known gaps: the source publishes 2023 results only to 2023-03-28 (a source gap, not a filter); 2020 ends 2020-03-12 (season cancelled). Both are listed in research/COVERAGE.md and DATA_QUALITY.md.');
    p();
  }
  if (dq) {
    const q = {}; for (const s of dq.seasons) for (const [k, v] of Object.entries(s.by_quality || {})) q[k] = (q[k] || 0) + v;
    p('Reconciliation states over all seasons: ' + Object.entries(q).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${int(v)}`).join(' · ') + '.');
    p();
  }
  if (rules) {
    const rr = rules.run_rule;
    p(`Rules measured from ${int(rules.games_with_lines)} games with reconciled inning lines: the ten-run rule after seven ended ${pct(rr.all.stopped / rr.all.eligible)} of eligible games (conference ${pct(rr.conf.stopped / rr.conf.eligible)}, non-conference ${pct(rr.nonconf.stopped / rr.nonconf.eligible)}, inferred NCAA tournament ${rr.ncaa_tourney.stopped} of ${rr.ncaa_tourney.eligible}); extra half-innings average ${rules.extra_inning_runs.mean} runs vs ${rules.extra_inning_runs.regulation_mean} in regulation (no automatic runner).`);
    p();
  }

  /* ---------------------------------------------------------------- 4 team models */
  p('## 4. Team models — walk-forward');
  p();
  if (wf) {
    const W = wf.windows;
    p(`Training: every model is refitted day by day on all games available before 14:00 UTC on the game date, from ${C.SEASONS.first} (burn-in ${W.burn_in ? W.burn_in.join('–') : '2012–2013'}). Tuning: SELECTION only. Calibration maps for season S: seasons S−3..S−1 only. Ensemble weights: SELECTION. Leakage audit: ${wf.leakage.ok ? 'no violation' : 'VIOLATIONS ' + wf.leakage.violations} over ${int(wf.data.games_scored)} scored games.`);
    p();
    const sel = wf.windows_report.SELECTION; const val = wf.windows_report.VALIDATION;
    const names = Object.keys(val.models).sort((a, b) => (val.models[a].log_loss || 9) - (val.models[b].log_loss || 9));
    const hv = hold && !hold.withheld;
    p(`SELECTION ${sel.seasons[0]}–${sel.seasons[sel.seasons.length - 1]} (n ${int(sel.n)}), VALIDATION ${val.seasons.join('–')} (n ${int(val.n)})${hv ? `, HOLDOUT ${hold.seasons.join('–')} (n ${int(hold.n)})` : ''}. Lower log loss and Brier are better; calibration-in-the-large 0 and slope 1 are perfect.`);
    p();
    p(table(['Model', 'Description', 'SELECTION log loss', 'VALIDATION log loss', 'Brier', 'Cal. in the large', 'Slope'].concat(hv ? ['HOLDOUT log loss'] : []), names.map((n) => {
      const v = val.models[n];
      return ['`' + n + '`' + (n === wf.selection.chosen ? ' (chosen)' : '') + (n === pricing ? ' (prices)' : ''), describe(n), f5(sel.models[n] && sel.models[n].log_loss), f5(v.log_loss), f5(v.brier), f4(v.calibration_in_the_large), f4(v.calibration_slope)].concat(hv ? [f5(hold.models[n] && hold.models[n].log_loss)] : []);
    })));
    p();
    p('Paired comparisons (log loss, date-block bootstrap; negative = the first model is better):');
    p();
    const rows = [];
    for (const w of Object.keys(wf.comparisons)) for (const [k, c] of Object.entries(wf.comparisons[w])) if (c) rows.push([w, k.replace(/_/g, ' '), int(c.n), ci(c), verdict(c)]);
    p(table(['Window', 'Comparison', 'n', 'Mean difference', 'Verdict'], rows));
    p();
    const sl = val.chosen_slices;
    if (sl) {
      p(`Slices of the chosen model on VALIDATION (log loss; mean p vs mean outcome):`);
      p();
      const sr = []; for (const [dim, groups] of Object.entries(sl)) { if (dim === 'home_conference') continue; for (const [g, m] of Object.entries(groups)) sr.push([dim.replace(/_/g, ' '), g.replace(/_/g, ' '), int(m.n), f5(m.log_loss), f4(m.mean_p) + ' / ' + f4(m.mean_y)]); }
      p(table(['Slice', 'Group', 'n', 'Log loss', 'Mean p / outcome'], sr));
      p();
    }
    const bins = val.models[wf.selection.chosen].bins;
    if (bins && bins.length) {
      p('Reliability of the chosen model on VALIDATION:');
      p();
      p(table(['Bin', 'n', 'Mean p', 'Observed'], bins.filter((b) => b.n).map((b) => [`${f4(b.lo)}–${f4(b.hi)}`, int(b.n), f4(b.mean_p), f4(b.observed) + (b.inside ? '' : ' (outside the Wilson interval)')])));
      p();
    }
  } else p('Not run.');
  if (tuning) {
    p('Tuned hyperparameters (SELECTION log loss; the last round was time-boxed, so values on a grid edge are listed in research/UNRESOLVED.md rather than chased):');
    p();
    p(table(['Model', 'Configuration', 'SELECTION log loss', 'Configurations evaluated'], Object.entries(tuning.models).map(([n, t]) => ['`' + n + '`', '`' + JSON.stringify(t.cfg) + '`', f5(t.selection_log_loss), String(t.evaluated)])));
    p();
  }

  /* ---------------------------------------------------------------- 5 distribution */
  p('## 5. Run distribution');
  p();
  if (dist) {
    p(`Fitted on ${dist.fitted_on}. Chosen: **${dist.chosen}** ${JSON.stringify(dist.chosen_spec)}. Overdispersion (Pearson, 1 = Poisson): ${dist.dispersion.selection.pearson_dispersion} on SELECTION, ${dist.dispersion.validation.pearson_dispersion} on VALIDATION. Correlation of the two sides' residuals: ${dist.dispersion.validation.residual_correlation}.`);
    p();
    const v = dist.scores.VALIDATION;
    p(table(['Family (VALIDATION)', 'Team-runs log score', 'Total log score', 'Total RPS', '80% interval coverage', 'Moneyline log loss', 'P(total ≥ 20) pred / obs', 'P(shutout) pred / obs'], Object.entries(v).map(([k, s]) => [k, f5(s.team_runs_log_score), f5(s.total_log_score), f5(s.total_rps), pct(s.total_coverage_80), f5(s.moneyline_log_loss), `${f4(s.tails.p_total_ge_20)} / ${f4(s.tails.obs_total_ge_20)}`, `${f4(s.tails.p_shutout)} / ${f4(s.tails.obs_shutout)}`])));
    p();
  } else p('Not run.');

  /* ---------------------------------------------------------------- 6 pricing engine and simulator */
  p('## 6. Pricing engine: closed form and simulator');
  p();
  if (sim && sim.full_game) {
    const fg = sim.full_game; const c = fg.comparisons; const lv = sim.level_check;
    p(`${sim.window}; ${int(sim.n)} games, ${sim.sims_per_game} draws each. Every full-game market is priced from the closed form (the negative-binomial distribution mixed over rating uncertainty and scheduled length, at the pricing model's expectations); the inning simulator prices only the first five innings. Decision: full game — **${sim.decision.full_game_engine}**; first five — **${sim.decision.first_five_engine}**.`);
    p();
    p(table(['Market (VALIDATION)', 'Closed form', 'Simulator', 'Simulator on calibrated inputs', 'Closed form − simulator', 'Verdict'], [
      ['Moneyline log loss', f5(fg.moneyline_log_loss.closed_form), f5(fg.moneyline_log_loss.simulator), f5(fg.moneyline_log_loss.simulator_on_calibrated_inputs), ci(c.moneyline_cf_vs_sim), verdict(c.moneyline_cf_vs_sim)],
      ['Total-runs log score', f5(fg.total_log_score.closed_form), f5(fg.total_log_score.simulator), f5(fg.total_log_score.simulator_on_calibrated_inputs), ci(c.total_cf_vs_sim), verdict(c.total_cf_vs_sim)],
      ['Home −1.5 log loss', f5(fg.home_minus_1_5.closed_form.log_loss), f5(fg.home_minus_1_5.simulator.log_loss), f5(fg.home_minus_1_5.simulator_on_calibrated_inputs.log_loss), ci(c.run_line_cf_vs_sim), verdict(c.run_line_cf_vs_sim)],
      ['Moneyline calibration-in-the-large', f4(fg.moneyline.closed_form.citl), f4(fg.moneyline.simulator.citl), f4(fg.moneyline.simulator_on_calibrated_inputs.citl), '', ''],
    ]));
    p();
    const k = sim.construction;
    if (k) {
      const kc = k.comparisons; const lab = { calibrated_expectations: 'the calibrated expectations', reweighted_raw: 'the run model\'s own expectations re-weighted to the validated P(home)' };
      p(`Which expectations the closed form uses (every VALIDATION game, n ${int(k.n)}; same moneyline either way). Chosen: **${lab[k.decision]}**. Differences are re-weighted minus calibrated; negative favours re-weighting.`);
      p();
      p(table(['Market', 'Calibrated expectations', 'Re-weighted own expectations', 'Difference', 'Verdict'], [
        ['Total-runs log score', f5(k.total_log_score.calibrated_expectations), f5(k.total_log_score.reweighted_raw), ci(kc.total), verdict(kc.total)],
        ['Team-runs log score', f5(k.team_runs_log_score.calibrated_expectations), f5(k.team_runs_log_score.reweighted_raw), ci(kc.team_runs), verdict(kc.team_runs)],
        ['Home −1.5 log loss', f5(k.home_minus_1_5.calibrated_expectations.log_loss), f5(k.home_minus_1_5.reweighted_raw.log_loss), ci(kc.run_line_minus), verdict(kc.run_line_minus)],
        ['Home −1.5 calibration-in-the-large', f4(k.home_minus_1_5.calibrated_expectations.citl), f4(k.home_minus_1_5.reweighted_raw.citl), '', ''],
        ['Home +1.5 log loss', f5(k.home_plus_1_5.calibrated_expectations.log_loss), f5(k.home_plus_1_5.reweighted_raw.log_loss), ci(kc.run_line_plus), verdict(kc.run_line_plus)],
        ['Expected home runs (observed ' + k.expected_runs.home.observed + ')', String(k.expected_runs.home.calibrated_expectations), String(k.expected_runs.home.reweighted_raw), '', ''],
        ['Expected away runs (observed ' + k.expected_runs.away.observed + ')', String(k.expected_runs.away.calibrated_expectations), String(k.expected_runs.away.reweighted_raw), '', ''],
      ]));
      p();
    }
    p(`Why the simulator is fed the run model's own expectations: the run-space calibration moves the expectations so the closed form's P(home) is right, which leaves them biased in level (home ${lv.cal_lh} vs ${lv.actual_home} scored, away ${lv.cal_la} vs ${lv.actual_away}; the raw model: ${lv.raw_lh} and ${lv.raw_la}). The simulator models the home side's unplayed or cut-short last inning itself, so the calibrated inputs count that effect twice: on them it favours the home side (calibration-in-the-large ${f4(fg.moneyline.simulator_on_calibrated_inputs.citl)}), and on the raw ones it is better by ${ci(c.moneyline_sim_vs_sim_on_calibrated_inputs)}.`);
    p();
    p(`First five innings (simulator only): home-win log loss ${f5(sim.first_five.home_win.log_loss)}, calibration-in-the-large ${f4(sim.first_five.home_win.citl)}, slope ${f4(sim.first_five.home_win.slope)}; tie calibration-in-the-large ${f4(sim.first_five.tie.citl)}. Walk-off share predicted ${sim.walkoff_share.predicted} vs observed ${sim.walkoff_share.observed}; run-rule share predicted ${sim.run_rule_share.predicted} vs observed ${sim.run_rule_share.observed}. Coherence failures of the combined price: ${sim.coherence_failures}.`);
    p();
    p(table(['Draws', 'Mean first-five P(home)', 'Spread over 4 seeds', 'Theoretical SE'], sim.convergence.map((x) => [int(x.n), f4(x.mean_f5_home), f4(x.seed_spread), f4(x.theoretical_se)])));
    p();
    p('The spread over seeds exceeds the sampling SE because every run also recalibrates its inning rates on its own pilot draws; the full-game prices carry no Monte Carlo error at all.');
    p();
  } else p('Not run.');

  /* ---------------------------------------------------------------- 7 pitchers */
  p('## 7. Starting pitching, bullpen and workload');
  p();
  if (pw) {
    const s = pw.windows_report.SELECTION; const fit = pw.windows_report.FIT;
    p(`Box-score window: fitted on ${fit.seasons.join(', ')} (n ${int(fit.n)}), chosen on ${s.seasons.join(', ')} (n ${int(s.n)})${pw.windows_report.HOLDOUT ? `, holdout ${pw.windows_report.HOLDOUT.seasons.join(', ')} (n ${int(pw.windows_report.HOLDOUT.n)})` : ''}. Starters are PROJECTED from rotation patterns; the oracle (the actual starter) is a measurement of what confirmation would be worth, never a candidate.`);
    p();
    const ws = ['SELECTION'].concat(pw.windows_report.HOLDOUT ? ['HOLDOUT'] : []);
    p(table(['Variant'].concat(ws.flatMap((w) => [w + ' log loss', w + ' Brier'])), Object.keys(s.models).map((k) => ['`' + k + '`'].concat(ws.flatMap((w) => [f5(pw.windows_report[w].models[k].log_loss), f5(pw.windows_report[w].models[k].brier)])))));
    p();
    p(table(['Comparison', 'Window', 'Mean difference', 'Verdict'], ws.flatMap((w) => Object.entries(pw.windows_report[w].comparisons).map(([k, c]) => [k.replace(/_/g, ' '), w, ci(c), verdict(c)]))));
    p();
    const sp = pw.starter_projection.SELECTION.all;
    p(`Chosen: \`${pw.selection.chosen}\`. Starter projection on ${s.seasons.join(', ')}: top-1 accuracy ${pct(sp.top1_accuracy)} (mean stated probability ${pct(sp.mean_top_p)}), ${pct(sp.unseen_share)} of starts by a pitcher outside the recent rotation. Bullpen availability model: log loss ${pw.availability_calibration.log_loss} vs ${pw.availability_calibration.climatology_log_loss} climatology, slope ${pw.availability_calibration.slope}.`);
    p();
  } else p('Not run.');

  /* ---------------------------------------------------------------- 8 features, ML */
  p('## 8. Offense, defence, environment, machine learning, ensemble');
  p();
  if (fr) {
    const h = fr.hypotheses;
    p(table(['Hypothesis', 'Fit → test', 'n (test)', 'Difference in team-runs log score', 'Decision'], [
      ['H-OFF-1 component offense (blend)', `${h['H-OFF-1'].fit_season} → ${h['H-OFF-1'].test_season}`, int(h['H-OFF-1'].n_test), ci(h['H-OFF-1'].blend_vs_team), h['H-OFF-1'].decision],
      ['H-OFF-1 component offense alone', `${h['H-OFF-1'].fit_season} → ${h['H-OFF-1'].test_season}`, int(h['H-OFF-1'].n_test), ci(h['H-OFF-1'].component_vs_team), 'worse than the team model'],
      ['H-DEF-1 defence', `${h['H-DEF-1'].fit_season} → ${h['H-DEF-1'].test_season}`, int(h['H-DEF-1'].n_test), ci(h['H-DEF-1'].defence_vs_team), h['H-DEF-1'].decision],
      ['H-ENV-1 rest / doubleheader', `${h['H-ENV-1'].fit} → ${h['H-ENV-1'].test}`, int(h['H-ENV-1'].n_test), ci(h['H-ENV-1'].rest_vs_team), h['H-ENV-1'].decision],
    ]));
    p();
    p('H-OFF-1 is accepted as a finding but is not in the price: its only test season (2025) is the box-score SELECTION season, and it needs a season it has never seen before it may price (research/DECISIONS.md D-18).');
    p();
  }
  if (ml) {
    const v = ml.windows.VALIDATION;
    p(`Learners fitted on ${ml.fitted_on}, scored on ${ml.scored_on} (n ${int(v.n)}). Features: ${ml.features.join(', ')}.`);
    p();
    p(table(['Model', 'Log loss', 'Brier', 'Cal. in the large', 'Slope'], Object.entries(v.models).map(([k, m]) => ['`' + k + '`', f5(m.log_loss), f5(m.brier), f4(m.citl), f4(m.slope)])));
    p();
    p(table(['Comparison', 'Mean difference', 'Verdict'], Object.entries(v.comparisons).map(([k, c]) => [k.replace(/_/g, ' '), ci(c), verdict(c)])));
    p();
    p(`Decisions: GLM ${ml.decisions.glm}, boosting ${ml.decisions.gbm}, ensemble ${ml.decisions.ensemble}. Rule: ${ml.decisions.rule}. Ensemble weights (intercept first) ${JSON.stringify(ml.ensemble.weights)}; their spread across three-season blocks is reported in validation/ml_ensemble.json so instability is visible.`);
    p();
  }

  /* ---------------------------------------------------------------- 9 ablations */
  p('## 9. Ablations');
  p();
  if (abl) {
    p(`${abl.window}, n ${int(abl.n)}; full hierarchical model log loss ${f5(abl.full_log_loss)}. Positive difference = removing the component makes the model worse.`);
    p();
    p(table(['Removed', 'Log loss', 'Difference vs full', 'Verdict'], abl.results.map((x) => [x.removed, f5(x.log_loss), ci({ mean_diff: x.diff_vs_full, ci95: x.ci95 }), x.verdict])));
    p();
  } else p('Not run.');

  /* ---------------------------------------------------------------- 10 audit, gates */
  p('## 10. Adversarial audit and release gates');
  p();
  if (audit) {
    p(table(['Audit check', 'Critical', 'Status', 'Threshold'], audit.checks.map((c) => [c.id.replace(/_/g, ' ').toLowerCase(), c.critical ? 'yes' : '', c.status, c.threshold])));
    p();
  } else p('Audit not run.');
  if (gates) {
    p(table(['Gate', 'Status', 'Why'], gates.gates.map((g) => [g.id + ' ' + g.name, g.status, g.why])));
    p();
  } else p('Release gates not run.');

  /* ---------------------------------------------------------------- 11 board */
  p('## 11. Batch inference and the board');
  p();
  if (idx) {
    p(`Mode: **${idx.mode}** (${idx.point_in_time}) — ${idx.mode_note} Season ${idx.season}: ${int(idx.counts.games)} games, ${int(idx.counts.priced)} priced (${int(idx.counts.provisional)} provisional), ${int(idx.counts.blocked)} blocked with a stated reason, ${idx.failures.length} failures, ${idx.coherence_failures} incoherent price sets. Value claims: ${idx.value_claims} (${idx.value_reason}). Latency: ${JSON.stringify(idx.latency_ms)}.`);
    p();
  } else p('Not run.');

  /* ---------------------------------------------------------------- 12 registry */
  p('## 12. Experiment registry');
  p();
  const byDec = {}; for (const x of reg) byDec[x.decision] = (byDec[x.decision] || 0) + 1;
  p(`${reg.length} experiments (latest revision of each); ${Object.entries(byDec).map(([k, v]) => `${k} ${v}`).join(', ')}. Hash chain: ${chain && chain.ok ? 'verified' : 'NOT verified'}. Holdout looks recorded: ${reg.filter((x) => x.holdout_evaluated).map((x) => x.id).join(', ') || 'none'}. Rejected and inconclusive experiments are listed in research/FAILED_EXPERIMENTS.md.`);
  p();

  /* ---------------------------------------------------------------- 13 tests */
  p('## 13. Tests');
  p();
  if (tests) {
    p(`Run ${String(tests.ran_at).slice(0, 19)}Z on commit ${String(tests.commit || '').slice(0, 10)} by \`node tools/college_baseball/run_tests.js\`:`);
    p();
    const st = (s) => (s.ok ? 'PASS' : s.skipped ? 'SKIPPED' : 'FAIL');
    const cnt = (s) => (s.passed == null ? '—' : `${s.passed} passed${s.failed != null ? ', ' + s.failed + ' failed' : ''}`);
    const ex = tests.suites.existing_sports;
    p(table(['Suite', 'Result', 'Checks'], [['college baseball engine', st(tests.suites.college_baseball), cnt(tests.suites.college_baseball)], ['college baseball terminal (Chromium)', st(tests.suites.ui), cnt(tests.suites.ui)]]
      .concat(ex ? ex.results.map((r) => [r.file, st(r), cnt(r)]) : [])));
    p();
  } else p('Test results not recorded yet.');

  /* ---------------------------------------------------------------- 14 weaknesses */
  p('## 14. Weaknesses and limitations');
  p();
  [
    'Every evaluation is a retrospective reconstruction: the source can revise box scores, and nothing carries a publication timestamp (`known_at` is blank).',
    'No market test of any kind. Beating Elo is not beating a sportsbook; the model may be far worse than a market price.',
    'Commercial rights to NCAA-derived statistics are unverified (gate G1); nothing may be shown commercially until an owner decides.',
    'Starting pitchers are projected (about half correct), never confirmed; the pitcher engines did not significantly improve the moneyline and are not in the price.',
    'Box scores exist only for 2024–2026, so every pitcher, offense and defence result rests on one fit season and one test season.',
    'The 2023 season ends 2023-03-28 in the source, which thins VALIDATION and the 2024 priors.',
    'Run rules by conference and by series day are not in the source; the run-rule probability is measured per context (conference, non-conference, NCAA tournament) and pooled over seasons.',
    'No weather, lineups, injuries or travel. A college game can turn on all of them.',
    'Tuning stopped after a time-boxed third round with some values on grid edges; the optimum may lie beyond them (research/UNRESOLVED.md).',
    'Settlement profiles are unverified templates; extra innings, suspended games and run-rule settlement differ by book and are not confirmed.',
    sim && sim.construction ? `Home run lines at -1.5 are over-predicted by ${f4(sim.construction.home_minus_1_5[sim.construction.decision].citl)} (calibration-in-the-large): the closed form gives home wins margins that are too large, because it does not model the unplayed bottom ninth or regulation walk-offs (U-14).` : 'Run lines have not been checked for calibration.',
    (() => { const tc = audit && audit.checks.find((c) => c.id === 'TAILS'); if (!tc || tc.status === 'PASS') return 'The scoring-distribution tails pass the audit.'; const e = tc.evidence.tails; return `The negative binomial's right tail is too heavy for one side: P(side >= 15) ${pct(e.p_side_ge_15)} predicted vs ${pct(e.obs_side_ge_15)} observed. The critical TAILS check fails, so the auditor refused to promote this version (U-15); its prices are shown, labelled provisional research.`; })(),
    'First-five prices are research only: the inning simulator gets their level right but makes them too extreme, and no calibration map for them has been fitted yet (U-13).',
    sim && sim.decision && sim.decision.full_game_construction === 'reweighted_raw' ? 'The run-space calibration fixes P(home) by moving the run ratio, which biases each side\'s expected runs in level; the board therefore prices from the run model\'s own expectations re-weighted to the validated P(home) (section 6), which is measured, not assumed, to be better.' : 'The run-space calibration fixes P(home) by moving the run ratio, which leaves each side\'s expected runs biased in level (home too high, away too low); team totals and run lines inherit that bias.',
  ].forEach((s) => p('- ' + s));
  p();
  p('## 15. Reproduce');
  p();
  p('`college_baseball/research/REPRODUCE.md` lists the exact commands, in order. Deployment and rollback: `docs/college-baseball/DEPLOYMENT.md`.');
  p();
  return L.join('\n');
}

