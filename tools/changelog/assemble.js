#!/usr/bin/env node
/* ============================================================================
   EdgeDesk — CHANGELOG.md, assembled from changelog.d/.

   WHY. Eight of the ten pull requests merged on 2026-10-26 added an entry at
   the top of CHANGELOG.md. Every one of them conflicted there, the conflicts
   were resolved by hand, and four entries were dropped and restored in three
   follow-up commits (#799's merge ffc4047085 dropped #801's, #799's, #797's
   and the exhibitions entry). A file every pull request edits in the same
   place cannot be merged safely, however careful the resolver is.

   THE FIX. A pull request adds ONE NEW FILE, changelog.d/<date>-<slug>.md,
   holding its entry exactly as it should read:

       ## 2026-10-26 — The headline, in the house style

       The body, in Markdown.

   Two pull requests add two different files, so they never conflict. On main,
   the Changelog workflow (.github/workflows/changelog.yml) renders every
   fragment into the marked block at the top of CHANGELOG.md and commits it.
   CHANGELOG.md belongs to that job (tools/integrity/ownership.js reads it
   from the workflow): the integrity gate refuses a pull request that edits it
   directly. The entries below the block are the history before fragments.

   Order: newest date first; within a date, an entry already in the block
   keeps its place and a new one goes on top, so the block reads in the order
   entries reached main. Fragments are never deleted: they are the source,
   and the block is rebuilt from them byte for byte.

     node tools/changelog/assemble.js --new "Headline"   create today's fragment
     node tools/changelog/assemble.js --validate         check every fragment
     node tools/changelog/assemble.js --check            exit 1 if the block is stale
     node tools/changelog/assemble.js --write            rewrite the block
   ============================================================================ */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const START = '<!-- changelog.d:start — generated by tools/changelog/assemble.js from changelog.d/. Add a file there; do not edit between these markers. -->';
const END = '<!-- changelog.d:end -->';
const NAME_RE = /^(\d{4}-\d{2}-\d{2})-[a-z0-9][a-z0-9-]*\.md$/;
const HEAD_RE = /^## (\d{4}-\d{2}-\d{2}) — (\S.*)$/;
const MARK_RE = /^<!-- changelog\.d\/([^ ]+\.md) -->$/;

function validDate(d) {
  const t = Date.parse(d + 'T00:00:00Z');
  return Number.isFinite(t) && new Date(t).toISOString().slice(0, 10) === d;
}

/* One fragment: { name, date, title, text, problems[] } */
function parseFragment(name, text) {
  const problems = [];
  const nm = NAME_RE.exec(name);
  if (!nm) problems.push('the file name must be YYYY-MM-DD-some-slug.md (lowercase letters, digits and hyphens): ' + name);
  const body = text.replace(/^﻿/, '').replace(/\r\n/g, '\n').replace(/\s+$/, '');
  const lines = body.split('\n');
  const first = lines.findIndex((l) => l.trim() !== '');
  const hm = first >= 0 ? HEAD_RE.exec(lines[first]) : null;
  if (!hm) problems.push('the first line must be "## YYYY-MM-DD — Headline" (an em dash between date and headline)');
  if (hm && !validDate(hm[1])) problems.push('the heading date is not a calendar date: ' + hm[1]);
  if (hm && nm && hm[1] !== nm[1]) problems.push('the heading date ' + hm[1] + ' differs from the file name date ' + nm[1]);
  const rest = lines.slice(first + 1);
  if (rest.some((l) => /^#\s/.test(l))) problems.push('a fragment holds no level-1 heading (the changelog has one: "# Changelog")');
  if (rest.some((l) => /^##\s/.test(l))) problems.push('one entry per fragment: a second "## " heading starts another entry — make it its own file');
  if (!rest.some((l) => l.trim())) problems.push('the entry has a headline but no body');
  if (lines.some((l) => l === START || l === END || MARK_RE.test(l))) problems.push('a fragment cannot contain the changelog block markers');
  return { name, date: hm ? hm[1] : (nm ? nm[1] : '0000-00-00'), title: hm ? hm[2] : '', text: lines.slice(first < 0 ? 0 : first).join('\n'), problems };
}

function readFragments(root) {
  const dir = path.join(root || ROOT, 'changelog.d');
  let names = [];
  try { names = fs.readdirSync(dir); } catch (e) { names = []; }
  return names.filter((n) => n.endsWith('.md') && n !== 'README.md').sort()
    .map((n) => parseFragment(n, fs.readFileSync(path.join(dir, n), 'utf8')));
}

function split(changelog) {
  const a = changelog.indexOf(START);
  const b = changelog.indexOf(END);
  if (a < 0 || b < 0 || b < a) throw new Error('CHANGELOG.md has no changelog.d block (the two marker comments)');
  return { before: changelog.slice(0, a), block: changelog.slice(a + START.length, b), after: changelog.slice(b + END.length) };
}

/* The order the block holds now: fragment names, top first. */
function currentOrder(block) {
  return block.split('\n').map((l) => MARK_RE.exec(l.trim())).filter(Boolean).map((m) => m[1]);
}

function render(fragments, previousOrder) {
  const pos = new Map((previousOrder || []).map((n, i) => [n, i]));
  const sorted = fragments.slice().sort((x, y) => {
    if (x.date !== y.date) return x.date < y.date ? 1 : -1;
    const px = pos.has(x.name), py = pos.has(y.name);
    if (px !== py) return px ? 1 : -1;                    // new entries on top of their date
    if (px && py) return pos.get(x.name) - pos.get(y.name);
    return x.name < y.name ? 1 : -1;
  });
  if (!sorted.length) return '\n';
  return '\n' + sorted.map((f) => '<!-- changelog.d/' + f.name + ' -->\n' + f.text + '\n').join('\n') + '\n';
}

function assemble(changelog, fragments) {
  const s = split(changelog);
  return s.before + START + render(fragments, currentOrder(s.block)) + END + s.after;
}

function slugify(t) {
  return t.toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60).replace(/-+$/, '') || 'change';
}

module.exports = { START, END, parseFragment, readFragments, render, assemble, currentOrder, split, slugify };

if (require.main === module) {
  const args = process.argv.slice(2);
  const file = path.join(ROOT, 'CHANGELOG.md');
  const frags = readFragments(ROOT);
  const bad = frags.filter((f) => f.problems.length);
  if (args[0] === '--new') {
    const title = args.slice(1).join(' ').trim();
    if (!title) { console.error('usage: assemble.js --new "Headline"'); process.exit(64); }
    const date = new Date().toISOString().slice(0, 10);
    let name = date + '-' + slugify(title) + '.md';
    for (let i = 2; fs.existsSync(path.join(ROOT, 'changelog.d', name)); i++) name = date + '-' + slugify(title) + '-' + i + '.md';
    fs.mkdirSync(path.join(ROOT, 'changelog.d'), { recursive: true });
    fs.writeFileSync(path.join(ROOT, 'changelog.d', name), '## ' + date + ' — ' + title + '\n\nWhat changed, why, and how it was tested.\n');
    console.log('changelog.d/' + name);
    process.exit(0);
  }
  if (bad.length) {
    bad.forEach((f) => f.problems.forEach((p) => console.error('changelog.d/' + f.name + ': ' + p)));
    process.exit(1);
  }
  if (args[0] === '--validate') { console.log(frags.length + ' changelog fragment(s) valid'); process.exit(0); }
  const cur = fs.readFileSync(file, 'utf8');
  const next = assemble(cur, frags);
  if (args[0] === '--check') {
    if (next === cur) { console.log('CHANGELOG.md is up to date with ' + frags.length + ' fragment(s)'); process.exit(0); }
    const have = new Set(currentOrder(split(cur).block));
    const missing = frags.filter((f) => !have.has(f.name)).map((f) => f.name);
    console.error('CHANGELOG.md is stale' + (missing.length ? '; not yet assembled: ' + missing.join(', ') : ' (an entry changed)'));
    process.exit(1);
  }
  if (args[0] === '--write') {
    if (next !== cur) fs.writeFileSync(file, next);
    console.log((next === cur ? 'unchanged' : 'wrote CHANGELOG.md') + ' (' + frags.length + ' fragment(s))');
    process.exit(0);
  }
  console.error('usage: assemble.js --new "Headline" | --validate | --check | --write');
  process.exit(64);
}
