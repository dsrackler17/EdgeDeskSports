#!/usr/bin/env node
/* ===========================================================================
   MODEL REGISTRY — every model identity EdgeDesk has actually published under,
   from the committed ledgers. docs/market-intelligence/model_registry.json
   (generated by this file). The foundation MASTER_PLAN.md §8 calls for.

   engine/registry.json describes each sport's DESIGNED model. This answers a
   different question: which model ids and versions appear on published
   forecasts, where, when, how often, and under how many spellings, and which
   models can be compared because they priced the same games.

     identities     one row per (sport, canonical model id): every raw label it
                    was written under, the ledgers it appears in, first and last
                    publication, forecast and event counts, evaluation modes
     label_issues   one model written under two names, or a version on the
                    record that the ledger names differently
     comparisons    live pairs on common games at one fixed checkpoint (the
                    CFB Lab's T24): paired MAE difference with a week-cluster
                    bootstrap interval, and the correlation of their errors.
                    Only same-games, same-checkpoint numbers; never a ranking
                    across sports or windows.

   No score is invented for a model with no graded forecasts; no model is
   ranked against one it cannot be compared with.

   Run:  node tools/market_intel/model_registry.js [--write]
   =========================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const L = require(path.join(ROOT, 'lib', 'edgedesk_validation_lab.js'));
const OUT = path.join(ROOT, 'docs', 'market-intelligence', 'model_registry.json');
const SEASON = 2026;

const ms = (t) => { const v = t == null ? NaN : Date.parse(t); return isFinite(v) ? v : null; };
const isNum = (x) => typeof x === 'number' && isFinite(x);
const mean = (a) => (a.length ? a.reduce((s, v) => s + v, 0) / a.length : null);
function jsonl(p) { const f = path.join(ROOT, p); return fs.existsSync(f) ? fs.readFileSync(f, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)) : []; }
function iso(t) { return t == null ? null : new Date(t).toISOString(); }

/* One model, one key: a version written as "xg_core" by one capture and
   "edgedesk_nhl_v1:xg_core" by another is the same model. */
function canonical(sport, id, version) {
  const s = String(version || id || '').trim();
  const prefix = { nhl: 'edgedesk_nhl_v1:', nba: 'edgedesk_nba_v1:', wnba: 'edgedesk_bb_points_v1:' }[sport];
  if (prefix && s && !/^edgedesk_/.test(s)) return prefix + s;
  return s || null;
}

function collect() {
  const ids = {};
  function add(sport, raw, key, src, mode, at, event) {
    if (!key) return;
    const k = sport + '|' + key;
    const r = ids[k] = ids[k] || { sport, model: key, labels: {}, sources: {}, modes: {}, first: null, last: null, forecasts: 0, events: new Set() };
    r.labels[raw] = (r.labels[raw] || 0) + 1;
    r.sources[src] = (r.sources[src] || 0) + 1;
    r.modes[mode] = (r.modes[mode] || 0) + 1;
    const t = ms(at);
    if (t != null) { if (r.first == null || t < r.first) r.first = t; if (r.last == null || t > r.last) r.last = t; }
    r.forecasts++;
    if (event) r.events.add(event);
  }
  ['cfb', 'nfl', 'nba', 'nhl', 'wnba'].forEach((sp) => {
    jsonl('performance/ledger/forecasts/' + sp + '-' + SEASON + '.jsonl').forEach((f) => {
      const raw = f.model.id + (f.model.version && f.model.version !== f.model.id ? ' · ' + f.model.version : '');
      const mode = (f.capture || {}).method === 'ledger_capture' ? 'LIVE (performance ledger, verified)' : 'LIVE_RECONSTRUCTED (imported, ' + ((f.capture || {}).method || '?') + ')';
      /* the identity is model.id: model.version holds the model version on one capture path and a
         feature, artifact or distribution version on another (edgedesk_fbs_universe_v1.0.0, nfl_fv1,
         edgedesk_nba_dist_v1), so it is kept as a label, never used as the key */
      add(sp, raw, canonical(sp, f.model.id, null), 'performance/ledger/forecasts/' + sp + '-' + SEASON + '.jsonl', mode, f.model.predicted_at, f.event_key);
    });
  });
  ['cfb', 'nfl'].forEach((sp) => {
    const rec = JSON.parse(fs.readFileSync(path.join(ROOT, 'record', 'football', sp + '_' + SEASON + '.json'), 'utf8'));
    Object.values(rec.games).forEach((g) => {
      ['first', 'pick'].forEach((k) => { if (g[k] && g[k].model_version) add(sp, g[k].model_version, g[k].model_version, 'record/football/' + sp + '_' + SEASON + '.json', 'LIVE (football record)', g[k].at, sp.toUpperCase() + '|' + g.game_id); });
    });
  });
  const dir = path.join(ROOT, 'football', 'cfb_lab', 'ledger', String(SEASON), 'predictions');
  const lab = [];
  if (fs.existsSync(dir)) fs.readdirSync(dir).sort().forEach((f) => jsonl(path.relative(ROOT, path.join(dir, f))).forEach((p) => {
    lab.push(p);
    add('cfb', p.model_version, p.model_version, 'football/cfb_lab/ledger/' + SEASON + '/predictions', p.origin === 'LIVE' ? 'LIVE (CFB Lab)' : p.origin === 'REPLAY' ? 'BACKTEST (CFB Lab replay)' : 'LIVE_RECONSTRUCTED (CFB Lab, ' + p.origin + ')', p.prediction_ts, 'CFB|' + p.game_id);
  }));
  return { ids, lab };
}

/* the same game priced under two names in two ledgers */
function labelIssues(ids) {
  const out = [];
  const semantics = [];
  Object.values(ids).forEach((r) => {
    const names = Object.keys(r.labels);
    if (names.length > 1) semantics.push({ sport: r.sport, model: r.model, labels: r.labels });
  });
  if (semantics.length) out.push({ issue: 'the performance ledger\'s model.version field means the model version on one capture path and a feature, artifact or distribution version on another; model.id is consistent, so it is the identity here', severity: 'minor', models: semantics });
  /* NFL: the record names the version per game; the performance ledger names the slate header */
  const rec = JSON.parse(fs.readFileSync(path.join(ROOT, 'record', 'football', 'nfl_' + SEASON + '.json'), 'utf8'));
  const v2From = Object.values(rec.games).filter((g) => g.pick && /nfl_v2/.test(g.pick.model_version || '')).map((g) => ms(g.pick.at)).filter(isNum);
  if (v2From.length) {
    const since = Math.min.apply(null, v2From);
    const mis = jsonl('performance/ledger/forecasts/nfl-' + SEASON + '.jsonl').filter((f) => ms(f.model.predicted_at) >= since && !/nfl_v2/.test(f.model.id));
    if (mis.length) out.push({ sport: 'nfl', model: 'edgedesk_nfl_v2.1.0', severity: 'major', issue: 'performance-ledger forecasts made after the record first names edgedesk_nfl_v2.1.0 (' + iso(since) + ') carry the slate header\'s ' + mis[0].model.id
      + '; fixed forward in lib/edgedesk_projections.js (2026-10-23); the ledger is append-only, so these rows keep their label and this entry is the correction', rows: mis.length, first: iso(Math.min.apply(null, mis.map((f) => ms(f.model.predicted_at)))), last: iso(Math.max.apply(null, mis.map((f) => ms(f.model.predicted_at)))) });
  }
  return out;
}

/* live CFB Lab models, same games, one checkpoint */
function comparisons(lab, checkpoint) {
  const results = {};
  jsonl('football/cfb_lab/ledger/' + SEASON + '/results.jsonl').forEach((r) => { if (r.status === 'FINAL' && isNum(r.final_margin)) results[r.game_id] = r; });
  const by = {};
  lab.filter((p) => p.origin === 'LIVE' && p.checkpoint_type === checkpoint && ms(p.prediction_ts) < ms(p.kickoff_ts) && isNum(p.pure_home_margin)).forEach((p) => {
    const k = p.model_version + '|' + p.game_id;
    if (!by[k] || ms(p.prediction_ts) > ms(by[k].prediction_ts)) by[k] = p;
  });
  const models = [...new Set(Object.values(by).map((p) => p.model_version))].sort();
  const out = [];
  for (let i = 0; i < models.length; i++) for (let j = i + 1; j < models.length; j++) {
    const a = models[i], b = models[j];
    const rows = [];
    Object.values(by).filter((p) => p.model_version === a).forEach((pa) => {
      const pb = by[b + '|' + pa.game_id], res = results[pa.game_id];
      if (!pb || !res) return;
      rows.push({ cluster: 'w' + pa.week, ea: res.final_margin - pa.pure_home_margin, eb: res.final_margin - pb.pure_home_margin });
    });
    const d = L.pairedDifference(rows, (r) => Math.abs(r.ea), (r) => Math.abs(r.eb), { cluster: 'cluster' });
    const ea = rows.map((r) => r.ea), eb = rows.map((r) => r.eb), ma = mean(ea), mb = mean(eb);
    let sab = 0, saa = 0, sbb = 0;
    rows.forEach((r) => { sab += (r.ea - ma) * (r.eb - mb); saa += (r.ea - ma) ** 2; sbb += (r.eb - mb) ** 2; });
    out.push({ checkpoint, a, b, common_games: rows.length, clusters: d.clusters, mae_a: L.round(d.a_mean, 3), mae_b: L.round(d.b_mean, 3),
      mae_diff_a_minus_b: L.rounded(d.diff, 3), verdict: d.verdict, error_correlation: rows.length > 2 && saa > 0 && sbb > 0 ? L.round(sab / Math.sqrt(saa * sbb), 3) : null });
  }
  return { checkpoint, models, pairs: out, note: 'Live CFB Lab predictions at the ' + checkpoint + ' checkpoint, each model\'s latest pregame number per game, graded on the CFB Lab results ledger. An error correlation near 1 means the two models make the same mistakes: averaging them would add little.' };
}

function run() {
  const { ids, lab } = collect();
  const identities = Object.values(ids).map((r) => ({ sport: r.sport, model: r.model, labels: r.labels, sources: r.sources, modes: r.modes,
    first_published: iso(r.first), last_published: iso(r.last), forecasts: r.forecasts, events: r.events.size }))
    .sort((a, b) => a.sport < b.sport ? -1 : a.sport > b.sport ? 1 : (a.first_published || '') < (b.first_published || '') ? -1 : 1);
  return { schema: 'edgedesk_model_registry_v1', season: SEASON, lab: L.VERSION,
    what: 'Every model identity on a committed 2026 forecast, the labels it was written under, and the live pairs that can be compared on the same games. engine/registry.json holds each sport\'s design; this holds what was published.',
    graded_record: { 'model versus market': 'docs/market-intelligence/VALIDATION.md', 'CFB Lab live record': 'football/cfb_lab/ledger/' + SEASON + '/evaluations.jsonl', 'historical champion / challenger (CFB)': 'docs/cfb-v2/CHAMPION_CHALLENGER.md' },
    identities, label_issues: labelIssues(ids), comparisons: comparisons(lab, 'T24') };
}

if (require.main === module) {
  const rep = run();
  if (process.argv.includes('--write')) { fs.writeFileSync(OUT, JSON.stringify(rep, null, 1) + '\n'); console.log('wrote ' + path.relative(ROOT, OUT)); }
  rep.identities.forEach((r) => console.log(r.sport.padEnd(5) + r.model.padEnd(42) + String(r.forecasts).padStart(6) + ' forecasts ' + String(r.events).padStart(5) + ' events  ' + Object.keys(r.labels).length + ' label(s)'));
  rep.label_issues.forEach((x) => console.log('ISSUE ' + (x.sport || '') + ' ' + (x.model || '') + ': ' + x.issue.slice(0, 160)));
  rep.comparisons.pairs.forEach((p) => console.log('T24 ' + p.a + ' vs ' + p.b + ': n ' + p.common_games + ' MAE ' + p.mae_a + ' vs ' + p.mae_b + ' diff ' + p.mae_diff_a_minus_b.est + ' [' + p.mae_diff_a_minus_b.ci + '] ' + p.verdict + ' corr ' + p.error_correlation));
}
module.exports = { run, canonical };
