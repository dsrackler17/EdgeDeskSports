#!/usr/bin/env node
/* ===========================================================================
   MODEL VERSUS MARKET — the validation report, from committed ledgers only.
   docs/market-intelligence/VALIDATION.md (generated by this file)

   Reads, never writes, the point-in-time records already in the repository:

     record/football/{cfb,nfl}_<season>.json   the football model's LAST
                pregame number (the "pick", always before kickoff), the first
                model+market pair ("entry"), the close and the final
     performance/ledger/{forecasts,quotes,results}/<sport>-<season>.jsonl
                the hash-chained performance ledger: every pregame forecast,
                every captured DraftKings quote (via ESPN) and the verified
                final, for the probability sports (NHL, NBA, WNBA)

   and asks, per sport, the questions docs/market-intelligence/MASTER_PLAN.md
   puts first: does the model beat the market benchmark on the same games,
   does its disagreement with the market carry information, is it
   calibrated, and where is it biased. Every figure carries n, the number of
   clusters (a football week, a calendar day of the slate in US Eastern
   time) and a 95% cluster-bootstrap interval.

   The benchmark rule is fixed here, before any outcome is read:
     close        football: the record's closing line (DraftKings via ESPN
                  for CFB, the nflverse consensus for the NFL); probability
                  sports: the last DraftKings quote observed before the start
     at_forecast  the last quote observed at or before the forecast time
   The best book is never chosen after the fact.

   Hypotheses come from docs/market-intelligence/hypotheses.json, written
   before this report is run; each is judged on its own window and the
   verdict (ACCEPTED, REJECTED, INSUFFICIENT_EVIDENCE) is recorded beside it.
   Nothing here edits a hypothesis, a model or a ledger.

   Run:  node tools/market_intel/validation_report.js           (summary)
         node tools/market_intel/validation_report.js --write   (the doc + json)
         node tools/market_intel/validation_report.js --json    (json to stdout)
   =========================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const L = require(path.join(ROOT, 'lib', 'edgedesk_validation_lab.js'));
const C = require(path.join(ROOT, 'lib', 'edgedesk_calc.js'));
const V = require(path.join(ROOT, 'lib', 'edgedesk_validation.js'));
const OUT_DIR = path.join(ROOT, 'docs', 'market-intelligence');
const HYP = path.join(OUT_DIR, 'hypotheses.json');
const SEASON = 2026;
const SCHEMA = 'edgedesk_model_vs_market_v1';

const ms = (t) => { const v = t == null ? NaN : Date.parse(t); return isFinite(v) ? v : null; };
const isNum = (x) => typeof x === 'number' && isFinite(x);
const mean = (a) => (a.length ? a.reduce((s, v) => s + v, 0) / a.length : null);
const r = L.round;
function readJson(p) { return JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8')); }
function readJsonl(p) {
  const f = path.join(ROOT, p);
  if (!fs.existsSync(f)) return [];
  return fs.readFileSync(f, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
}
const ET = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/New_York', year: 'numeric', month: '2-digit', day: '2-digit' });
function slateDay(iso) { const t = ms(iso); return t == null ? null : ET.format(new Date(t)); }
function noVigHome(home, away) { const p = C.noVigTwoWay(home, away); return p ? p.a : null; }

/* ------------------------------------------------------------ football */
function footballRows(sport) {
  const file = 'record/football/' + sport + '_' + SEASON + '.json';
  const j = readJson(file);
  const rows = [], excluded = {};
  const skip = (why) => { excluded[why] = (excluded[why] || 0) + 1; };
  Object.values(j.games).forEach((g) => {
    if (!g.final || g.final.home_score == null) return skip('no verified final');
    if (!g.pick || g.pick.home_line == null) return skip('no pregame model number');
    if (!g.close || g.close.home_line == null) return skip('no closing line');
    const kick = ms(g.kickoff), at = ms(g.pick.at);
    if (kick == null || at == null || at >= kick) return skip('model number not provably before kickoff');
    const margin = g.final.home_score - g.final.away_score, total = g.final.home_score + g.final.away_score;
    const pr = g.close.prices || {};
    const entry = g.entry && g.entry.market && g.entry.market.home_line != null && ms(g.entry.model_at) != null && ms(g.entry.model_at) < kick ? g.entry : null;
    rows.push({
      sport, game_id: g.game_id, week: g.week, cluster: 'w' + g.week, kickoff: g.kickoff, model_version: g.pick.model_version || g.model_version,
      group: g.group || null, matchup: g.matchup_type || null,
      margin, total,
      model_margin: -g.pick.home_line, close_margin: -g.close.home_line,
      model_total: isNum(g.pick.total) ? g.pick.total : null, close_total: isNum(g.close.total) ? g.close.total : null,
      model_p: isNum(g.pick.home_win_prob) ? g.pick.home_win_prob : null,
      market_p: noVigHome(pr.home_ml, pr.away_ml),
      outcome: margin === 0 ? null : margin > 0 ? 1 : 0,
      entry_model_margin: entry ? -entry.home_line : null, entry_market_margin: entry ? -entry.market.home_line : null,
      close_source: (g.close.source || '?') + '/' + (g.close.book || '?')
    });
  });
  return { file, rows, excluded, close_sources: count(rows.map((x) => x.close_source)), versions: count(rows.map((x) => x.model_version)) };
}
function count(xs) { const o = {}; xs.forEach((x) => { o[x] = (o[x] || 0) + 1; }); return o; }

/* ------------------------------------------------- performance ledger */
function ledgerRows(sport) {
  const F = readJsonl('performance/ledger/forecasts/' + sport + '-' + SEASON + '.jsonl');
  const Q = readJsonl('performance/ledger/quotes/' + sport + '-' + SEASON + '.jsonl');
  const R = readJsonl('performance/ledger/results/' + sport + '-' + SEASON + '.jsonl');
  const res = {};
  R.forEach((x) => { if (!res[x.event_key] || (x.revision || 0) > (res[x.event_key].revision || 0)) res[x.event_key] = x; });
  const qBy = {};
  Q.forEach((q) => { if (q.moneyline && isNum(q.moneyline.home) && isNum(q.moneyline.away)) (qBy[q.event_key] = qBy[q.event_key] || []).push(q); });
  const fBy = {};
  F.forEach((f) => { (fBy[f.event_key] = fBy[f.event_key] || []).push(f); });
  const rows = [], excluded = {};
  const skip = (why) => { excluded[why] = (excluded[why] || 0) + 1; };
  Object.keys(fBy).forEach((k) => {
    const start = fBy[k][0].start_utc, st = ms(start);
    const pre = fBy[k].filter((f) => ms(f.model.predicted_at) != null && ms(f.model.predicted_at) < st && isNum(f.forecast.p_home));
    if (!pre.length) return skip('no pregame probability');
    const last = pre.sort((a, b) => ms(a.model.predicted_at) - ms(b.model.predicted_at))[pre.length - 1];
    const fin = res[k];
    if (!fin || fin.state !== 'FINAL') return skip('no verified final');
    const margin = fin.home_score - fin.away_score;
    const close = L.marketAt(qBy[k] || [], start, { start });
    const atf = L.marketAt(qBy[k] || [], last.model.predicted_at, { start });
    rows.push({
      sport, event_key: k, start, cluster: slateDay(start), model_version: last.model.version,
      model_p: last.forecast.p_home, outcome: margin === 0 ? null : margin > 0 ? 1 : 0, decided: fin.decided || null,
      close_p: close.quote ? noVigHome(close.quote.moneyline.home, close.quote.moneyline.away) : null,
      close_age_min: close.quote ? close.age_minutes : null,
      at_forecast_p: atf.quote ? noVigHome(atf.quote.moneyline.home, atf.quote.moneyline.away) : null,
      forecast_tier: last.capture && last.capture.method && /^import/.test(last.capture.method) ? 'RECORDED' : 'VERIFIED',
      model_total: isNum(last.forecast.expected_total) ? last.forecast.expected_total : null, total: fin.home_score + fin.away_score
    });
  });
  return { files: ['forecasts', 'quotes', 'results'].map((d) => 'performance/ledger/' + d + '/' + sport + '-' + SEASON + '.jsonl'), rows, excluded,
    versions: count(rows.map((x) => x.model_version)), quoted: rows.filter((x) => x.close_p != null).length };
}

/* ------------------------------------------------------------- the tests
   Every test takes rows and returns a result with a verdict. They are named
   so a hypothesis can point at one. */
const absErr = (a, b) => (isNum(a) && isNum(b) ? Math.abs(a - b) : null);
function meanBoot(rows, f) {
  const xs = rows.map((x) => ({ v: f(x), cluster: x.cluster })).filter((x) => isNum(x.v));
  const b = L.clusterBootstrap(xs, (s) => mean(s.map((x) => x.v)), { cluster: 'cluster' });
  const enough = b.n >= L.MIN.n && b.clusters >= L.MIN.clusters;
  b.verdict = !enough ? 'INSUFFICIENT_EVIDENCE' : L.excludesZero(b) ? (b.ci[1] < 0 ? 'BELOW_ZERO' : 'ABOVE_ZERO') : 'ZERO_NOT_EXCLUDED';
  return b;
}
const favSign = (x) => (x.close_margin === 0 ? null : Math.sign(x.close_margin));
const TESTS = {
  /* spreads: (model margin, close margin, final margin) */
  spread_mae_vs_close: (rows) => L.pairedDifference(rows, (x) => absErr(x.model_margin, x.margin), (x) => absErr(x.close_margin, x.margin), { cluster: 'cluster' }),
  spread_info_vs_close: (rows) => L.informationTest(rows.map((x) => ({ model: x.model_margin, market: x.close_margin, actual: x.margin, cluster: x.cluster }))),
  spread_market_moves_toward_model: (rows) => L.informationTest(rows.map((x) => ({ model: x.entry_model_margin, market: x.entry_market_margin, actual: x.close_margin, cluster: x.cluster }))),
  spread_home_lean_vs_close: (rows) => meanBoot(rows, (x) => x.model_margin - x.close_margin),
  spread_home_result_vs_close: (rows) => meanBoot(rows, (x) => x.margin - x.close_margin),
  spread_favourite_lean_vs_close: (rows) => meanBoot(rows, (x) => (favSign(x) == null ? null : (x.model_margin - x.close_margin) * favSign(x))),
  spread_favourite_result_vs_close: (rows) => meanBoot(rows, (x) => (favSign(x) == null ? null : (x.margin - x.close_margin) * favSign(x))),
  /* totals */
  total_mae_vs_close: (rows) => L.pairedDifference(rows, (x) => absErr(x.model_total, x.total), (x) => absErr(x.close_total, x.total), { cluster: 'cluster' }),
  total_info_vs_close: (rows) => L.informationTest(rows.map((x) => ({ model: x.model_total, market: x.close_total, actual: x.total, cluster: x.cluster }))),
  /* win probability: model vs the no-vig benchmark on the same games */
  winprob_brier_vs_close: (rows) => L.pairedDifference(rows.filter((x) => x.outcome != null), (x) => brier(x.model_p, x.outcome), (x) => brier(mkt(x), x.outcome), { cluster: 'cluster' }),
  winprob_logloss_vs_close: (rows) => L.pairedDifference(rows.filter((x) => x.outcome != null), (x) => ll(x.model_p, x.outcome), (x) => ll(mkt(x), x.outcome), { cluster: 'cluster' }),
  winprob_brier_vs_at_forecast: (rows) => L.pairedDifference(rows.filter((x) => x.outcome != null), (x) => brier(x.model_p, x.outcome), (x) => brier(x.at_forecast_p, x.outcome), { cluster: 'cluster' }),
  winprob_info_vs_close: (rows) => L.informationTest(rows.filter((x) => x.outcome != null).map((x) => ({ model: x.model_p, market: mkt(x), actual: x.outcome, cluster: x.cluster }))),
  winprob_calibration: (rows) => L.calibrationFit(rows.map((x) => ({ p: x.model_p, y: x.outcome, cluster: x.cluster }))),
  winprob_market_calibration: (rows) => L.calibrationFit(rows.map((x) => ({ p: mkt(x), y: x.outcome, cluster: x.cluster })))
};
function mkt(x) { return x.market_p != null ? x.market_p : x.close_p; }
function brier(p, y) { return isNum(p) && (y === 0 || y === 1) ? (p - y) * (p - y) : null; }
function ll(p, y) { if (!isNum(p) || (y !== 0 && y !== 1)) return null; const q = Math.min(1 - 1e-6, Math.max(1e-6, p)); return -(y * Math.log(q) + (1 - y) * Math.log(1 - q)); }

/* the slices each sport is cut by (descriptive; hypotheses name them) */
const SLICES = {
  all: () => true,
  fbs_vs_fbs: (x) => x.group !== 'fbs_fcs',
  fbs_vs_fcs: (x) => x.group === 'fbs_fcs',
  fav_0_3: (x) => Math.abs(x.close_margin) < 3.5,
  fav_3_7: (x) => Math.abs(x.close_margin) >= 3.5 && Math.abs(x.close_margin) < 7.5,
  fav_7_14: (x) => Math.abs(x.close_margin) >= 7.5 && Math.abs(x.close_margin) < 14.5,
  fav_14_21: (x) => Math.abs(x.close_margin) >= 14.5 && Math.abs(x.close_margin) < 21.5,
  fav_21_plus: (x) => Math.abs(x.close_margin) >= 21.5,
  /* the CFB engine changed its home field on 2026-10-19 (CHANGELOG): v1.0.0
     learned 3.2 and projected 4.082; v1.0.1 learns and projects one 2.8 */
  cfb_v1_0_0: (x) => x.model_version === 'edgedesk_cfb_p4_v1.0.0',
  cfb_v1_0_1: (x) => x.model_version === 'edgedesk_cfb_p4_v1.0.1',
  /* the home lean is read on FBS-vs-FBS games only: an FBS-vs-FCS game is
     nearly always an FBS home game the model prices short (H-003), which
     would pull a home lean down for a reason that has nothing to do with
     the home field */
  cfb_v1_0_1_fbs_vs_fbs: (x) => x.model_version === 'edgedesk_cfb_p4_v1.0.1' && x.group !== 'fbs_fcs'
};

/* -------------------------------------------------------- the datasets */
function datasets() {
  const cfb = footballRows('cfb'), nfl = footballRows('nfl');
  const nhl = ledgerRows('nhl'), nba = ledgerRows('nba'), wnba = ledgerRows('wnba');
  return {
    cfb: Object.assign({ kind: 'football_record', benchmark: 'closing line: DraftKings via ESPN; win probability: no-vig closing moneyline' }, cfb),
    nfl: Object.assign({ kind: 'football_record', benchmark: 'closing line: nflverse consensus; win probability: no-vig closing moneyline' }, nfl),
    nhl: Object.assign({ kind: 'performance_ledger', benchmark: 'no-vig DraftKings moneyline (via ESPN), last quote observed before the start' }, nhl),
    nba: Object.assign({ kind: 'performance_ledger', benchmark: 'no-vig DraftKings moneyline (via ESPN), last quote observed before the start' }, nba),
    wnba: Object.assign({ kind: 'performance_ledger', benchmark: 'no-vig DraftKings moneyline (via ESPN), last quote observed before the start' }, wnba)
  };
}
const PLAN = {
  cfb: { slices: ['all', 'fbs_vs_fbs', 'fbs_vs_fcs', 'cfb_v1_0_0', 'cfb_v1_0_1'], tests: ['spread_mae_vs_close', 'spread_info_vs_close', 'spread_market_moves_toward_model', 'spread_home_lean_vs_close', 'spread_home_result_vs_close',
    'total_mae_vs_close', 'total_info_vs_close', 'winprob_brier_vs_close', 'winprob_logloss_vs_close', 'winprob_info_vs_close', 'winprob_calibration', 'winprob_market_calibration'] },
  nfl: { slices: ['all'], tests: ['spread_mae_vs_close', 'spread_info_vs_close', 'spread_market_moves_toward_model', 'spread_home_lean_vs_close', 'spread_home_result_vs_close',
    'total_mae_vs_close', 'total_info_vs_close', 'winprob_brier_vs_close', 'winprob_logloss_vs_close', 'winprob_info_vs_close', 'winprob_calibration', 'winprob_market_calibration'] },
  nhl: { slices: ['all'], tests: ['winprob_brier_vs_close', 'winprob_logloss_vs_close', 'winprob_brier_vs_at_forecast', 'winprob_info_vs_close', 'winprob_calibration', 'winprob_market_calibration'] },
  nba: { slices: ['all'], tests: ['winprob_brier_vs_close', 'winprob_logloss_vs_close', 'winprob_info_vs_close', 'winprob_calibration'] },
  wnba: { slices: ['all'], tests: ['winprob_brier_vs_close', 'winprob_calibration'] }
};
const FAV_SLICES = ['fav_0_3', 'fav_3_7', 'fav_7_14', 'fav_14_21', 'fav_21_plus'];

function compact(res) {
  /* a test result, rounded, without the per-draw detail */
  const o = JSON.parse(JSON.stringify(res));
  const walk = (v) => {
    if (Array.isArray(v)) return v.map(walk);
    if (v && typeof v === 'object') { const w = {}; Object.keys(v).forEach((k) => { w[k] = walk(v[k]); }); return w; }
    return typeof v === 'number' ? r(v, 4) : v;
  };
  return walk(o);
}
function headline(res) {
  /* the one interval a hypothesis is judged on */
  if (!res) return null;
  const b = res.diff || res.slope_boot || res;
  const h = { est: res.diff ? res.diff.est : res.slope_boot ? res.slope : res.est, ci: b.ci, verdict: res.verdict, n: res.n,
    clusters: res.clusters != null ? res.clusters : b.clusters, few_clusters: !!b.few_clusters, leave_one_out: b.leave_one_out || null,
    why: (res.diff && res.diff.why) || res.why || null };
  if (!h.n) h.why = 'no games in the window yet';
  return h;
}

function run() {
  const D = datasets();
  const results = {};
  Object.keys(PLAN).forEach((sport) => {
    const rows = D[sport].rows;
    results[sport] = {};
    PLAN[sport].slices.forEach((sl) => {
      const sub = rows.filter(SLICES[sl]);
      results[sport][sl] = { n: sub.length, state: V.sampleState(sub.length).key, tests: {} };
      PLAN[sport].tests.forEach((t) => { results[sport][sl].tests[t] = TESTS[t](sub); });
    });
    if (D[sport].kind === 'football_record') {
      results[sport].favourites = FAV_SLICES.map((sl) => {
        const sub = rows.filter(SLICES[sl]);
        return { slice: sl, n: sub.length, lean: TESTS.spread_favourite_lean_vs_close(sub), result: TESTS.spread_favourite_result_vs_close(sub),
          model_mae: r(mean(sub.map((x) => absErr(x.model_margin, x.margin))), 2), close_mae: r(mean(sub.map((x) => absErr(x.close_margin, x.margin))), 2) };
      });
    }
  });

  /* the family of information tests, adjusted together (Benjamini–Hochberg) */
  const fam = [];
  Object.keys(results).forEach((sp) => Object.keys(results[sp]).forEach((sl) => {
    const tests = results[sp][sl].tests || {};
    if (/^cfb_v1/.test(sl)) return;   /* a version slice repeats 'all' (410 of 417 games): not a separate test */
    Object.keys(tests).forEach((t) => { if (/_info_|moves_toward/.test(t) && tests[t].verdict !== 'INSUFFICIENT_EVIDENCE') fam.push({ key: sp + '.' + sl + '.' + t, p: tests[t].p_normal }); });
  }));
  const adj = L.adjust(fam.map((f) => f.p), 'bh');
  fam.forEach((f, i) => { f.p_bh = adj[i]; });

  /* hypotheses: each judged on its own window, never edited */
  const H = fs.existsSync(HYP) ? JSON.parse(fs.readFileSync(HYP, 'utf8')) : { hypotheses: [] };
  const judged = H.hypotheses.map((h) => {
    const chk = L.checkHypothesis(h);
    if (!chk.ok) return { id: h.id, status: null, why: chk.problems.join('; ') };
    const rows = (D[h.data.sport] ? D[h.data.sport].rows : []).filter(SLICES[h.data.slice || 'all']).filter((x) => {
      const t = ms(x.kickoff || x.start);
      return (!h.window || !h.window.from || t >= ms(h.window.from)) && (!h.window || !h.window.to || t < ms(h.window.to));
    });
    const res = TESTS[h.data.test] ? TESTS[h.data.test](rows) : null;
    const hl = headline(res);
    const j = res ? L.judge(h, hl) : { status: null, why: 'unknown test ' + h.data.test };
    return { id: h.id, kind: h.kind, statement: h.statement, status: j.status, why: j.why, result: hl ? compact(hl) : null };
  });

  const meta = {};
  Object.keys(D).forEach((k) => {
    meta[k] = { kind: D[k].kind, source: D[k].file || D[k].files, benchmark: D[k].benchmark, rows: D[k].rows.length, excluded: D[k].excluded,
      versions: D[k].versions, close_sources: D[k].close_sources || null, quoted: D[k].quoted != null ? D[k].quoted : null,
      first: D[k].rows.reduce((a, x) => { const t = x.kickoff || x.start; return !a || t < a ? t : a; }, null),
      last: D[k].rows.reduce((a, x) => { const t = x.kickoff || x.start; return !a || t > a ? t : a; }, null),
      clusters: new Set(D[k].rows.map((x) => x.cluster)).size };
  });
  const asOf = Object.values(meta).reduce((a, m) => (!a || (m.last && m.last > a) ? m.last : a), null);
  return { schema: SCHEMA, lab: L.VERSION, season: SEASON, data_through: asOf, bootstrap: { draws: L.DEFAULTS.draws, seed: L.DEFAULTS.seed, alpha: L.DEFAULTS.alpha },
    minimums: L.MIN, datasets: meta, results: compact(results), information_family: compact(fam), hypotheses: judged };
}

/* ------------------------------------------------------------ the doc */
function fmt(x, k) { return isNum(x) ? (k === 'pct' ? (100 * x).toFixed(1) + '%' : x.toFixed(k == null ? 2 : k)) : '—'; }
function ci(c, k) { return c && isNum(c[0]) ? '[' + fmt(c[0], k) + ', ' + fmt(c[1], k) + ']' : 'no interval'; }
/* † fewer than 10 clusters: the interval is approximate.
   ‡ the interval excludes zero but one cluster left out flips the sign. */
function cell(res, k) {
  const h = headline(res);
  if (!h) return '—';
  const lo = h.leave_one_out, excl = h.ci && isNum(h.ci[0]) && (h.ci[0] > 0 || h.ci[1] < 0);
  return fmt(h.est, k) + ' ' + ci(h.ci, k) + (h.few_clusters && isNum(h.ci && h.ci[0]) ? '†' : '') + (excl && lo && !lo.sign_stable ? '‡' : '');
}
function doc(rep) {
  const L2 = [];
  const p = (s) => L2.push(s);
  p('# Model versus market — validation');
  p('');
  p('Generated by `node tools/market_intel/validation_report.js --write` from committed ledgers; do not edit by hand. Methods and caveats: [`MASTER_PLAN.md`](MASTER_PLAN.md) §3 and the header of [`lib/edgedesk_validation_lab.js`](../../lib/edgedesk_validation_lab.js). Machine-readable: [`validation.json`](validation.json).');
  p('');
  p('**Data through ' + (rep.data_through || '—') + '.** Every interval is a 95% percentile interval from ' + rep.bootstrap.draws + ' cluster-bootstrap draws (seed ' + rep.bootstrap.seed + '); a cluster is a football week or a calendar day (US Eastern) of a slate, because games on one slate share a data refresh and a market regime. No verdict is stated below ' + rep.minimums.n + ' games in ' + rep.minimums.clusters + ' clusters (' + rep.minimums.calibration_n + ' for calibration). Sample states use `lib/edgedesk_validation.js` (a product maturity label, not a scientific verdict).');
  p('');
  p('† = fewer than 10 clusters, so the interval is approximate (a percentile cluster bootstrap under-covers with few clusters). ‡ = the interval excludes zero but leaving one cluster out flips the sign: not robust. A hypothesis is never ACCEPTED on a ‡ result (`judge()` in the lab).');
  p('');
  p('**This is one partial season of live, point-in-time data.** It is the right data (every model number was recorded before kickoff and every market number is a named source at a recorded time), but it is small. An interval that includes zero means *not demonstrated*, not *disproved*.');
  p('');
  p('## The data');
  p('');
  p('| sport | source | benchmark | games | clusters | first | last | model versions | excluded |');
  p('|---|---|---|---|---|---|---|---|---|');
  Object.keys(rep.datasets).forEach((k) => {
    const m = rep.datasets[k];
    p('| ' + k.toUpperCase() + ' | ' + (Array.isArray(m.source) ? m.source.map((s) => '`' + s + '`').join('<br>') : '`' + m.source + '`') + ' | ' + m.benchmark + (m.quoted != null ? ' (' + m.quoted + ' of the games quoted)' : '') + ' | ' + m.rows + ' | ' + m.clusters + ' | ' + (m.first || '—').slice(0, 10) + ' | ' + (m.last || '—').slice(0, 10) + ' | '
      + Object.keys(m.versions).map((v) => '`' + v + '` ' + m.versions[v]).join('<br>') + ' | ' + (Object.keys(m.excluded).map((e) => e + ': ' + m.excluded[e]).join('<br>') || '—') + ' |');
  });
  p('');
  p('## Spreads and totals (football): the model\'s last pregame number against the close');
  p('');
  p('Absolute-error difference = model MAE − close MAE on the same games (negative = the model was closer to the final). Information slope = the slope of (final − close) on (model − close): 0 means the model\'s disagreement carried nothing the close did not, 1 means following the model in full; "market moved toward model" regresses (close − first quote) on (model − first quote).');
  p('');
  p('| sport · slice | games | state | spread MAE diff (pts) | spread information slope | market moved toward model | model home lean vs close (pts) | final vs close, home (pts) | total MAE diff | total information slope |');
  p('|---|---|---|---|---|---|---|---|---|---|');
  ['cfb', 'nfl'].forEach((sp) => Object.keys(rep.results[sp]).filter((k) => k !== 'favourites').forEach((sl) => {
    const R2 = rep.results[sp][sl], t = R2.tests;
    p('| ' + sp.toUpperCase() + ' · ' + sl + ' | ' + R2.n + ' | ' + R2.state + ' | ' + cell(t.spread_mae_vs_close) + ' | ' + cell(t.spread_info_vs_close) + ' ' + t.spread_info_vs_close.verdict
      + ' | ' + cell(t.spread_market_moves_toward_model) + ' (n ' + t.spread_market_moves_toward_model.n + ') | ' + cell(t.spread_home_lean_vs_close) + ' | ' + cell(t.spread_home_result_vs_close)
      + ' | ' + cell(t.total_mae_vs_close) + ' | ' + cell(t.total_info_vs_close) + ' ' + t.total_info_vs_close.verdict + ' |');
  }));
  p('');
  p('### By favourite size (the closing line), in the favourite\'s points');
  p('');
  p('"Model lean" is the model\'s margin minus the close, signed so positive = the model liked the favourite more than the market. "Final vs close" is the same for the result. A model that inflates favourites shows a positive lean the result does not.');
  p('');
  p('| sport | favourite by | games | model lean (pts) | final vs close (pts) | model MAE | close MAE |');
  p('|---|---|---|---|---|---|---|');
  ['cfb', 'nfl'].forEach((sp) => rep.results[sp].favourites.forEach((b) => {
    p('| ' + sp.toUpperCase() + ' | ' + b.slice.replace('fav_', '').replace('_plus', '+').replace('_', '–') + ' | ' + b.n + ' | ' + cell(b.lean) + ' | ' + cell(b.result) + ' | ' + fmt(b.model_mae) + ' | ' + fmt(b.close_mae) + ' |');
  }));
  p('');
  p('## Win probability: the model against the no-vig market on the same games');
  p('');
  p('Brier / log-loss difference = model − market (negative = the model scored better). Calibration slope from y ~ a + b·logit(p): 1 is calibrated, below 1 overconfident.');
  p('');
  p('| sport · slice | games | model Brier | market Brier | Brier diff | log-loss diff | probability information slope | model calibration slope | verdict | market calibration slope |');
  p('|---|---|---|---|---|---|---|---|---|---|');
  Object.keys(rep.results).forEach((sp) => Object.keys(rep.results[sp]).filter((k) => k !== 'favourites').forEach((sl) => {
    const t = rep.results[sp][sl].tests;
    if (!t.winprob_brier_vs_close) return;
    const b = t.winprob_brier_vs_close, lgl = t.winprob_logloss_vs_close, cal = t.winprob_calibration, mc = t.winprob_market_calibration, inf = t.winprob_info_vs_close;
    p('| ' + sp.toUpperCase() + ' · ' + sl + ' | ' + b.n + ' | ' + fmt(b.a_mean, 4) + ' | ' + fmt(b.b_mean, 4) + ' | ' + cell(b, 4) + ' ' + b.verdict + ' | ' + (lgl ? cell(lgl, 4) : '—')
      + ' | ' + (inf ? cell(inf) + ' ' + inf.verdict : '—') + ' | ' + fmt(cal.slope) + ' ' + ci(cal.slope_boot && cal.slope_boot.ci) + ' | ' + cal.verdict + ' | ' + (mc ? fmt(mc.slope) + ' ' + ci(mc.slope_boot && mc.slope_boot.ci) : '—') + ' |');
  }));
  if (rep.results.nhl && rep.results.nhl.all.tests.winprob_brier_vs_at_forecast) {
    const a = rep.results.nhl.all.tests.winprob_brier_vs_at_forecast;
    p('');
    p('NHL against the quote available **when the forecast was made** (not the close): Brier diff ' + cell(a, 4) + ', n ' + a.n + ', ' + a.verdict + '.');
  }
  p('');
  p('## Multiple comparisons');
  p('');
  p('Every information test above with enough data is one member of a family; the p-values (normal approximation to the cluster-robust t) are adjusted together by Benjamini–Hochberg. A raw p below 0.05 that does not survive adjustment is not a finding.');
  p('');
  p('| test | raw p | BH-adjusted p |');
  p('|---|---|---|');
  rep.information_family.forEach((f) => p('| `' + f.key + '` | ' + fmt(f.p, 4) + ' | ' + fmt(f.p_bh, 4) + ' |'));
  p('');
  p('## Hypotheses');
  p('');
  p('From [`hypotheses.json`](hypotheses.json) (its `registration_note` says what was written when, and every amendment is listed on its hypothesis). EXPLORATORY hypotheses are judged on data that had already been played, and some had been looked at, so their result describes that data and confirms nothing. A CONFIRMATORY hypothesis was registered before any game in its window was played; it starts as INSUFFICIENT_EVIDENCE and is judged as games are played. A REJECTED hypothesis stays here.');
  p('');
  p('| id | kind | statement | status | estimate [95% CI] | n | why |');
  p('|---|---|---|---|---|---|---|');
  rep.hypotheses.forEach((h) => {
    const res = h.result || {};
    p('| ' + h.id + ' | ' + h.kind + ' | ' + h.statement + ' | **' + (h.status || 'INVALID') + '** | ' + (res.est != null ? fmt(res.est, 3) + ' ' + ci(res.ci, 3) : '—') + ' | ' + (res.n != null ? res.n : '—') + ' | ' + (h.why || '') + ' |');
  });
  p('');
  return L2.join('\n');
}

