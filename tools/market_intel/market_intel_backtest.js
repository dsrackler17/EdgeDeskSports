#!/usr/bin/env node
/* ===========================================================================
   MARKET INTELLIGENCE BACKTEST — what each kind of finding was worth, on the
   committed 2026 football quote ledgers. docs/market-intelligence/MARKET_INTEL_BACKTEST.md
   (generated by this file)

   For every graded CFB and NFL game with captured quotes, the engine
   (lib/edgedesk_market_intel.js) is run AS OF ONE HOUR BEFORE KICKOFF with:
     quotes     record/football/quotes/<sport>_2026.jsonl observed before then
     model      the football record's FIRST published number (first.at)
     history    each earlier game's first-to-last pregame move (games that
                kicked off before this one's as-of time only)
     fit        the spread–moneyline relationship from pairs observed before
                the as-of time (any game)
   Nothing after the as-of time is read for the finding; the final score and
   the close are read afterwards, only to measure it.

   The question for a movement finding is whether it carried information:
     market_improvement = |final − first quote| − |final − latest quote|
       (positive: the later price was nearer the result than the earlier one)
     model_vs_market    = |final − latest quote| − |final − EdgeDesk|
       (positive: EdgeDesk's number was nearer the result than the market's)
   Each with n, clusters (weeks) and a 95% cluster-bootstrap interval.

   EXPLORATORY: this is the first look at these findings on this data. A
   pattern here becomes a hypothesis in hypotheses.json for later games; it
   is not evidence by itself. Model calibration warnings are left out (the
   validation that would supply them reads the whole season, not the as-of).

   Run:  node tools/market_intel/market_intel_backtest.js [--write]
   =========================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const MI = require(path.join(ROOT, 'lib', 'edgedesk_market_intel.js'));
const L = require(path.join(ROOT, 'lib', 'edgedesk_validation_lab.js'));
const OUT = path.join(ROOT, 'docs', 'market-intelligence');
const SEASON = 2026, AS_OF_MIN = 60;
/* Both sides settle on the full game, overtime included (no ties in CFB; an NFL tie: the
   model counts half a win, a two-way moneyline pushes), so no football market here is a
   definition conflict. Recorded so the rule is evaluated, not skipped. */
const SETTLES = {
  cfb: { spread: 'FULL_GAME_INCL_OT', total: 'FULL_GAME_INCL_OT', moneyline: 'FULL_GAME_INCL_OT' },
  nfl: { spread: 'FULL_GAME_INCL_OT', total: 'FULL_GAME_INCL_OT', moneyline: 'FULL_GAME_INCL_OT_TIE_PUSH' }
};

const ms = (t) => { const v = t == null ? NaN : Date.parse(t); return isFinite(v) ? v : null; };
const isNum = (x) => typeof x === 'number' && isFinite(x);
const mean = (a) => (a.length ? a.reduce((s, v) => s + v, 0) / a.length : null);
function readJsonl(p) { const f = path.join(ROOT, p); return fs.existsSync(f) ? fs.readFileSync(f, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)) : []; }

function sportRun(sport) {
  const rec = JSON.parse(fs.readFileSync(path.join(ROOT, 'record', 'football', sport + '_' + SEASON + '.json'), 'utf8'));
  const Q = readJsonl('record/football/quotes/' + sport + '_' + SEASON + '.jsonl').filter((q) => q.is_pregame !== false);
  const qBy = {};
  Q.forEach((q) => { (qBy[q.game_id] = qBy[q.game_id] || []).push(q); });
  const games = Object.values(rec.games).filter((g) => g.final && g.final.home_score != null && qBy[g.game_id] && g.first && ms(g.first.at) != null)
    .sort((a, b) => ms(a.kickoff) - ms(b.kickoff));
  /* every (spread, moneyline) pair in the ledger, by observation time, for the walk-forward fit */
  const allPairs = MI.derivativePairs(Q).map((p) => Object.assign(p, { t: ms(p.observed_at) })).sort((a, b) => a.t - b.t);
  /* each game's first-to-last pregame move per market (its "history" contribution once it has kicked off) */
  const moveOf = {};
  games.forEach((g) => {
    const kick = ms(g.kickoff), mv = {};
    ['spread', 'total', 'moneyline'].forEach((m) => {
      const s = qBy[g.game_id].filter((q) => q.market_type === m && ms(q.observed_at) < kick).sort((a, b) => ms(a.observed_at) - ms(b.observed_at));
      if (s.length < 2) return;
      const v0 = MI.valueOf(normal(s[0]), m), v1 = MI.valueOf(normal(s[s.length - 1]), m);
      if (v0 != null && v1 != null) mv[m] = Math.abs(v1 - v0);
    });
    moveOf[g.game_id] = { kick, mv };
  });
  const rows = [], counts = {}, notEligible = {};
  games.forEach((g) => {
    const kick = ms(g.kickoff), asOf = kick - AS_OF_MIN * 60000;
    if (ms(g.first.at) >= asOf) return;
    const hist = { spread: [], total: [], moneyline: [] };
    games.forEach((h) => { if (h !== g && moveOf[h.game_id].kick < asOf) Object.keys(moveOf[h.game_id].mv).forEach((m) => hist[m].push(moveOf[h.game_id].mv[m])); });
    const fit = MI.fitDerivative(allPairs.filter((p) => p.t < asOf));
    const model = { home_margin: isNum(g.first.home_line) ? -g.first.home_line : null, fair_total: isNum(g.first.total) ? g.first.total : null,
      p_home: isNum(g.first.home_win_prob) ? g.first.home_win_prob : null, model_version: g.first.model_version || g.model_version, predicted_at: g.first.at };
    const res = MI.analyze({ sport, now: new Date(asOf).toISOString(), quotes: qBy[g.game_id],
      game: { event_key: sport.toUpperCase() + '|' + g.game_id, game_id: g.game_id, season: SEASON, kickoff: g.kickoff, home: g.home, away: g.away },
      model: Object.assign(model, { settles: SETTLES[sport] }), market_settles: SETTLES[sport],
      context: { movement_history: hist, derivative_fit: fit } });
    const margin = g.final.home_score - g.final.away_score, total = g.final.home_score + g.final.away_score;
    res.findings.forEach((f) => {
      counts[f.type] = (counts[f.type] || 0) + 1;
      const actual = f.market === 'spread' ? margin : f.market === 'total' ? total : f.market === 'moneyline' ? (margin === 0 ? null : margin > 0 ? 1 : 0) : null;
      const e = f.evidence || {};
      const first = isNum(e.market_then) ? e.market_then : isNum(e.first) ? e.first : null;
      const latest = isNum(e.market_now) ? e.market_now : isNum(e.latest) ? e.latest : null;
      const mod = f.market === 'spread' ? model.home_margin : f.market === 'total' ? model.fair_total : model.p_home;
      rows.push({ sport, game_id: g.game_id, week: g.week, cluster: 'w' + g.week, type: f.type, market: f.market, finding_id: f.finding_id,
        market_improvement: actual != null && first != null && latest != null ? Math.abs(actual - first) - Math.abs(actual - latest) : null,
        model_vs_market: actual != null && latest != null && isNum(mod) ? Math.abs(actual - latest) - Math.abs(actual - mod) : null,
        example: f.explain.what_changed });
    });
    res.not_eligible.forEach((n) => { const k = n.type + ' — ' + n.why.replace(/[0-9.]+/g, '#').replace(/^[a-z]+: /, ''); notEligible[k] = (notEligible[k] || 0) + 1; });
    rows.push({ sport, game_id: g.game_id, week: g.week, cluster: 'w' + g.week, type: '__game__', single_source: res.quality.single_source, history_n: hist.spread.length, fit_n: fit.n });
  });
  return { sport, games: rows.filter((r) => r.type === '__game__').length, rows: rows.filter((r) => r.type !== '__game__'), gameRows: rows.filter((r) => r.type === '__game__'), counts, notEligible };
}
function normal(q) { return { home_line: q.home_line, total: q.total_points != null ? q.total_points : q.total, price_home: q.price_home, price_away: q.price_away }; }

function meanBoot(rows, f) {
  const xs = rows.map((r) => ({ v: f(r), cluster: r.cluster })).filter((x) => isNum(x.v));
  const b = L.clusterBootstrap(xs, (s) => mean(s.map((x) => x.v)), { cluster: 'cluster' });
  return L.rounded(b, 3);
}

function run() {
  const out = { schema: 'edgedesk_market_intel_backtest_v1', engine: MI.VERSION, lab: L.VERSION, season: SEASON, as_of_minutes_before_kickoff: AS_OF_MIN, rules: MI.RULES, sports: {} };
  ['cfb', 'nfl'].forEach((sp) => {
    const R = sportRun(sp);
    const byType = {};
    Object.keys(MI.TYPES).forEach((t) => {
      const rs = R.rows.filter((r) => r.type === t);
      const games = new Set(rs.map((r) => r.game_id)).size;
      const markets = {};
      ['spread', 'total', 'moneyline', null].forEach((m) => {
        const sub = rs.filter((r) => r.market === m);
        if (!sub.length) return;
        markets[m || 'game'] = { findings: sub.length,
          market_improvement: /CONVERGENCE|DIVERGENCE|UNUSUAL/.test(t) ? meanBoot(sub, (r) => r.market_improvement) : null,
          model_vs_market: /CONVERGENCE|DIVERGENCE/.test(t) ? meanBoot(sub, (r) => r.model_vs_market) : null,
          examples: sub.slice(0, 2).map((r) => r.example) };
      });
      byType[t] = { findings: rs.length, games, share_of_games: R.games ? +(games / R.games).toFixed(3) : null, markets };
    });
    out.sports[sp] = { games_analyzed: R.games, single_source_games: R.gameRows.filter((g) => g.single_source).length,
      median_history_n: R.gameRows.length ? R.gameRows.map((g) => g.history_n).sort((a, b) => a - b)[Math.floor(R.gameRows.length / 2)] : null,
      by_type: byType, not_eligible: Object.fromEntries(Object.entries(R.notEligible).sort((a, b) => b[1] - a[1]).slice(0, 12)) };
  });
  return out;
}

function fmt(b) { if (!b || b.est == null) return '—'; return b.est.toFixed(2) + (b.ci && b.ci[0] != null ? ' [' + b.ci[0].toFixed(2) + ', ' + b.ci[1].toFixed(2) + ']' : ' (no interval)') + (b.few_clusters ? '†' : '') + (b.leave_one_out && !b.leave_one_out.sign_stable && b.ci && b.ci[0] != null && (b.ci[0] > 0 || b.ci[1] < 0) ? '‡' : '') + ' n ' + b.n; }
function doc(rep) {
  const o = [];
  const p = (s) => o.push(s);
  p('# Market intelligence — backtest of the findings');
  p('');
  p('Generated by `node tools/market_intel/market_intel_backtest.js --write`; do not edit by hand. Engine: `' + rep.engine + '` ([`lib/edgedesk_market_intel.js`](../../lib/edgedesk_market_intel.js)). Machine-readable: [`market_intel_backtest.json`](market_intel_backtest.json).');
  p('');
  p('**What was run.** Every graded ' + SEASON + ' CFB and NFL game with captured quotes, as of ' + rep.as_of_minutes_before_kickoff + ' minutes before kickoff: the quotes observed before then (DraftKings via ESPN, the only source in `record/football/quotes`), EdgeDesk\'s first published number, the moves of games that had already kicked off, and the spread–moneyline relationship fitted on earlier pairs. The final and the close are read only afterwards, to measure the finding.');
  p('');
  p('**EXPLORATORY.** First look, one source, a few weeks. † fewer than 10 week-clusters (approximate interval); ‡ not robust to dropping one week.');
  p('');
  p('*market improvement* = |final − first quote| − |final − latest quote| (points; positive = the later price was nearer the result). *model vs market* = |final − latest quote| − |final − EdgeDesk| (positive = EdgeDesk nearer the result).');
  p('');
  Object.keys(rep.sports).forEach((sp) => {
    const S = rep.sports[sp];
    p('## ' + sp.toUpperCase() + ' — ' + S.games_analyzed + ' games (' + S.single_source_games + ' single-source), median ' + S.median_history_n + ' earlier games in the movement history');
    p('');
    p('| finding | findings | games | share of games | market | market improvement | model vs market |');
    p('|---|---|---|---|---|---|---|');
    Object.keys(S.by_type).forEach((t) => {
      const b = S.by_type[t];
      const ms_ = Object.keys(b.markets);
      if (!ms_.length) { p('| ' + t + ' | 0 | 0 | 0 | — | — | — |'); return; }
      ms_.forEach((m, i) => {
        const x = b.markets[m];
        p('| ' + (i ? '' : t) + ' | ' + x.findings + ' | ' + (i ? '' : b.games) + ' | ' + (i ? '' : (100 * b.share_of_games).toFixed(1) + '%') + ' | ' + m + ' | ' + (x.market_improvement ? fmt(x.market_improvement) : '—') + ' | ' + (x.model_vs_market ? fmt(x.model_vs_market) : '—') + ' |');
      });
    });
    p('');
    p('Why a kind could not be evaluated (most common; counted per game and market, so one game can count three times):');
    p('');
    Object.keys(S.not_eligible).forEach((k) => p('- ' + k + ': ' + S.not_eligible[k]));
    p('');
  });
  return o.join('\n');
}

if (require.main === module) {
  const rep = run();
  if (process.argv.includes('--write')) {
    fs.writeFileSync(path.join(OUT, 'market_intel_backtest.json'), JSON.stringify(rep, null, 1) + '\n');
    fs.writeFileSync(path.join(OUT, 'MARKET_INTEL_BACKTEST.md'), doc(rep) + '\n');
    console.log('wrote docs/market-intelligence/MARKET_INTEL_BACKTEST.md');
  }
  Object.keys(rep.sports).forEach((sp) => {
    const S = rep.sports[sp];
    console.log(sp.toUpperCase(), 'games', S.games_analyzed);
    Object.keys(S.by_type).forEach((t) => { const b = S.by_type[t]; if (b.findings) console.log('  ' + t.padEnd(34) + String(b.findings).padStart(5) + ' findings in ' + b.games + ' games ' + Object.keys(b.markets).map((m) => m + ':' + (b.markets[m].market_improvement ? b.markets[m].market_improvement.est : '-') + '/' + (b.markets[m].model_vs_market ? b.markets[m].model_vs_market.est : '-')).join(' ')); });
  });
}
module.exports = { run, doc };
