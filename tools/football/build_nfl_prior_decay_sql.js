#!/usr/bin/env node
/* ===========================================================================
   supabase/nfl_prior_decay_registry.sql — GENERATED from
   football/research/nfl_v2/prior_decay/preregistration.json and results.json.
   Never hand-edit the SQL.

   It registers the v2 prior-decay study (H-NFL-PD-01) in the research registry
   through the same schema-reading SQL as the market-structure studies
   (tools/football/build_prereg_sql.js): one research_models row, one
   research_model_versions row (2.0.0-exp.1, status EXPERIMENTAL, provenance T3)
   carrying the decay schedule, the promotion criteria and the forking-paths
   disclosure (variants tried), and, once the backtest has run, one
   research_model_results row with passed = false. passed stays false until a
   finalist passes the 2025 holdout in a separate preregistered run. The status
   stays experimental either way, and nothing here touches a served number.

     node tools/football/build_nfl_prior_decay_sql.js           # write
     node tools/football/build_nfl_prior_decay_sql.js --check   # exit 1 if stale
   =========================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');
const G = require('./build_prereg_sql.js');
const ROOT = path.resolve(__dirname, '..', '..');
const DIR = path.join(ROOT, 'football', 'research', 'nfl_v2', 'prior_decay');
const PRE = path.join(DIR, 'preregistration.json');
const RES = path.join(DIR, 'results.json');
const OUT = path.join(ROOT, 'supabase', 'nfl_prior_decay_registry.sql');

/* the result row the backtest earned: metrics only, passed false (no holdout look) */
function resultRows() {
  if (!fs.existsSync(RES)) return null;
  const R = JSON.parse(fs.readFileSync(RES, 'utf8')), P = JSON.parse(fs.readFileSync(PRE, 'utf8'));
  if (R.preregistration.content_sha256 !== P.content_sha256) throw new Error('results.json was run against a different preregistration');
  const S = P.studies[0], pick = (x) => ({ label: x.label, k_db: x.k_db || null, valid: x.valid, clv: x.clv });
  return [{ study_id: S.id, version: S.machine.version, passed: false,
    metrics: { stage: 'A (validation 2010-2024)', holdout_looked: R.holdout_looked, variants_tried: R.variants_tried, selected: R.selected,
      verdict: R.verdict.finalist ? 'FINALIST' : 'REJECTED', checks: R.verdict.checks, seasons_brier_better: R.verdict.seasons_brier_better,
      incumbent: pick(R.incumbent), variants: R.variants.map(pick), generated_at: R.generated_at },
    notes: (R.verdict.finalist ? 'FINALIST at stage A; ' : 'REJECTED at stage A: ' + R.verdict.reason + '; ') + 'passed = false (the 2025 holdout has not been looked at); status stays experimental' }];
}
function header(J, sha) {
  const S = J.studies[0];
  return `-- =============================================================================
-- nfl_prior_decay_registry.sql — register the NFL v2 prior-decay study
-- (${S.id}) as EXPERIMENTAL in the research registry. docs/nfl-prior-decay/README.md
--
-- GENERATED by tools/football/build_nfl_prior_decay_sql.js from
-- football/research/nfl_v2/prior_decay/preregistration.json (content sha256
-- ${sha}) and its results.json. Do not edit by hand.
--
-- WHAT IT DOES. One research_models row (status EXPERIMENTAL, provenance T3)
-- and one research_model_versions row (version ${S.machine.version}, EXPERIMENTAL)
-- carrying the decay schedule, the windows, the minimum sample, the success
-- metric, the promotion criteria and the forking-paths disclosure
-- (${S.forking_paths.comparisons_made} variants), in whatever form the live columns take. When the
-- backtest has run, one research_model_results row with passed = false and the
-- validation metrics: passed turns true only after a holdout look this file
-- never makes.
--
-- WHAT IT DOES NOT DO. It changes no existing registry row and no served
-- weight. Nothing here touches a projection, spread, probability, EV,
-- ranking or grade.
--`;
}
function build() { return G.build({ pre: PRE, family: 'nfl_prior_decay', header, results: resultRows() }); }

if (require.main === module) {
  const sql = build();
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  if (process.argv.includes('--check')) { if (cur !== sql) { console.log('STALE ' + path.relative(ROOT, OUT) + ' (run node tools/football/build_nfl_prior_decay_sql.js)'); process.exit(1); } console.log('current'); process.exit(0); }
  if (cur === sql) console.log('unchanged ' + path.relative(ROOT, OUT));
  else { fs.writeFileSync(OUT, sql); console.log('wrote ' + path.relative(ROOT, OUT)); }
}
module.exports = { build, OUT, PRE, RES, resultRows };
