#!/usr/bin/env node
/* ===========================================================================
   supabase/nfl_market_structure_studies.sql — GENERATED from
   football/market_structure/preregistration.json. Never hand-edit the SQL.

   WHY GENERATED. The registry's own DDL (research_models,
   research_model_versions, research_model_results, research_model_current,
   the evidence_provenance and model_status enums) lives only in the
   production database; this repository reads it (app.html rsModelsLoad) but
   has never held it, and the app already reads its columns through fallback
   name lists. So the SQL does not assume a schema: it READS the live columns
   and enum labels, maps the four studies onto the names that exist, and
   refuses — naming the column — when a required column has no mapping. It
   writes no result row: a study is EXPERIMENTAL with no result until a
   validation report writes one.

     node tools/football/build_prereg_sql.js           # write
     node tools/football/build_prereg_sql.js --check   # exit 1 if stale
   =========================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const ROOT = path.resolve(__dirname, '..', '..');
const PRE = path.join(ROOT, 'football', 'market_structure', 'preregistration.json');
const OUT = path.join(ROOT, 'supabase', 'nfl_market_structure_studies.sql');

function build() {
  const J = JSON.parse(fs.readFileSync(PRE, 'utf8'));
  const sha = crypto.createHash('sha256').update(JSON.stringify(J.studies)).digest('hex');
  if (sha !== J.content_sha256) throw new Error('preregistration.json content_sha256 does not match its studies: an edit was made without a new version');
  const payload = JSON.stringify({ content_sha256: sha, registered_at: J.registered_at, frozen_protocol: J.frozen_protocol, family_correction: J.family_correction, studies: J.studies });
  if (payload.indexOf('$prereg$') >= 0) throw new Error('the payload contains the dollar-quote tag');
  const ids = J.studies.map((s) => "('" + s.id + "')").join(', ');
  return `-- =============================================================================
-- nfl_market_structure_studies.sql — register the four NFL Market Structure
-- studies as EXPERIMENTAL in the research registry. docs/market-structure/README.md
--
-- GENERATED by tools/football/build_prereg_sql.js from
-- football/market_structure/preregistration.json (content sha256
-- ${sha}). Do not edit by hand.
--
-- WHAT IT DOES. For each study (${J.studies.map((s) => s.id).join(', ')}):
-- one research_models row (status EXPERIMENTAL, provenance T3) and one
-- research_model_versions row (version 1.0.0-prereg, EXPERIMENTAL) carrying the
-- objective, the training / validation / holdout windows, the minimum sample,
-- the success metric, the decision rule and the forking-paths disclosure,
-- written in whatever form the live columns take (text, jsonb, a date range).
--
-- WHAT IT DOES NOT DO. It writes NO research_model_results row: there is no
-- result, so passed is absent and every reader (rsMaturity in app.html) reads
-- Experimental. It changes no existing registry row: a study already
-- registered is left exactly as it is and reported. Nothing here touches a
-- projection, spread, probability, EV, ranking or grade.
--
-- THE SCHEMA IS READ, NOT ASSUMED. The registry DDL is not in this repository.
-- The file reads the live columns and enum labels (pg_attribute, pg_enum) and
-- maps onto the names the app already reads; a NOT NULL column with no default
-- that it cannot fill stops the whole file with that column's name, before
-- anything is written.
--
-- CONVENTION (supabase/README.md): idempotent, additive, pasted into the SQL
-- editor, no psql meta-commands, ends in a report. Safe to run again.
-- =============================================================================

do $req$ begin
  if to_regclass('public.research_models') is null or to_regclass('public.research_model_versions') is null then
    raise exception 'the research registry (public.research_models, public.research_model_versions) is not in this database: nothing was registered';
  end if;
end $req$;

-- helpers for this session only (pg_temp: gone when the editor's session ends)
create or replace function pg_temp.edr_has(p_rel regclass, p_names text[]) returns text
language sql stable as $f$
  select u.n from unnest(p_names) with ordinality u(n, i)
   where exists (select 1 from pg_attribute a where a.attrelid = p_rel and a.attname = u.n and a.attnum > 0 and not a.attisdropped)
   order by u.i limit 1
$f$;
create or replace function pg_temp.edr_typ(p_rel regclass, p_col text) returns text
language sql stable as $f$
  select format_type(a.atttypid, a.atttypmod) from pg_attribute a where a.attrelid = p_rel and a.attname = p_col and a.attnum > 0 and not a.attisdropped
$f$;
-- an enum column takes the live label whose lower case is wanted; a text column takes the first wanted value
create or replace function pg_temp.edr_label(p_rel regclass, p_col text, p_wanted text[]) returns text
language plpgsql stable as $f$
declare t oid; l text;
begin
  select a.atttypid into t from pg_attribute a where a.attrelid = p_rel and a.attname = p_col and a.attnum > 0;
  if exists (select 1 from pg_type where oid = t and typtype = 'e') then
    select e.enumlabel into l from pg_enum e where e.enumtypid = t and lower(e.enumlabel) = any (p_wanted)
     order by array_position(p_wanted, lower(e.enumlabel)) limit 1;
    if l is null then
      raise exception 'research registry: %.% is an enum with no label for % (its labels: %) — nothing was registered', p_rel, p_col, p_wanted[1],
        (select string_agg(enumlabel, ', ' order by enumsortorder) from pg_enum where enumtypid = t);
    end if;
    return l;
  end if;
  return p_wanted[1];
end $f$;
-- a value shaped for the column it lands in
create or replace function pg_temp.edr_val(p_rel regclass, p_col text, p_text text, p_json jsonb, p_range jsonb) returns jsonb
language plpgsql stable as $f$
declare t text := pg_temp.edr_typ(p_rel, p_col);
begin
  if t is null then return null; end if;
  if t like '%range' then return case when p_range is null or jsonb_typeof(p_range) <> 'array' then 'null'::jsonb
    else to_jsonb('[' || (p_range ->> 0) || ',' || (p_range ->> 1) || ')') end; end if;
  if t = 'date' then return case when p_range is null or jsonb_typeof(p_range) <> 'array' then 'null'::jsonb else p_range -> 0 end; end if;
  if t in ('jsonb', 'json') then return coalesce(p_json, to_jsonb(p_text)); end if;
  if t in ('integer', 'bigint', 'smallint', 'numeric') then return case when jsonb_typeof(p_json) = 'number' then p_json else 'null'::jsonb end; end if;
  if t = 'boolean' then return case when jsonb_typeof(p_json) = 'boolean' then p_json else 'null'::jsonb end; end if;
  return to_jsonb(coalesce(p_text, p_json #>> '{}', p_json::text));
end $f$;
-- insert the listed columns only (so every other column keeps its own default);
-- refuse, by name, a required column with nothing to put in it
create or replace function pg_temp.edr_insert(p_rel regclass, p_vals jsonb, p_ret text) returns text
language plpgsql as $f$
declare cols text; missing text; out_ text;
begin
  select string_agg(quote_ident(k), ', ') into cols from jsonb_object_keys(p_vals) k;
  select string_agg(a.attname::text, ', ') into missing from pg_attribute a
   where a.attrelid = p_rel and a.attnum > 0 and not a.attisdropped and a.attnotnull and not a.atthasdef
     and a.attidentity = '' and a.attgenerated = '' and not (p_vals ? a.attname::text);
  if missing is not null then
    raise exception 'research registry: % requires % and this file has nothing to put there — nothing was registered (map it in tools/football/build_prereg_sql.js)', p_rel, missing;
  end if;
  execute format('insert into %s (%s) select %s from jsonb_populate_record(null::%s, $1) returning %I::text', p_rel, cols, cols, p_rel, p_ret) into out_ using p_vals;
  return out_;
end $f$;

begin;

do $reg$
declare
  S jsonb := $prereg$${payload}$prereg$::jsonb;
  m regclass := 'public.research_models';
  v regclass := 'public.research_model_versions';
  st jsonb; mv jsonb; vv jsonb; mach jsonb;
  kcol text; ncol text; refcol text; fkcol text; vcol text; c text; ref text; have boolean;
  n_models int := 0; n_versions int := 0; kept int := 0;
  pairs text[][] := array[
    array['training_window', 'train_window', 'training_period', 'training'],
    array['validation_window', 'valid_window', 'validation_period', 'validation'],
    array['holdout_window', 'holdout_period', 'holdout', 'test_window']];
  wkeys text[] := array['training', 'validation', 'holdout'];
  i int;
begin
  kcol := pg_temp.edr_has(m, array['model_key', 'key', 'model_name', 'model', 'slug', 'code', 'name']);
  if kcol is null then raise exception 'research registry: research_models has no key column (model_key, key, model_name, model, slug, code or name) — nothing was registered'; end if;
  select a.attname::text, ra.attname::text into fkcol, refcol
    from pg_constraint k
    join pg_attribute a on a.attrelid = k.conrelid and a.attnum = k.conkey[1]
    join pg_attribute ra on ra.attrelid = k.confrelid and ra.attnum = k.confkey[1]
   where k.contype = 'f' and k.conrelid = v and k.confrelid = m limit 1;
  if fkcol is null then
    fkcol := pg_temp.edr_has(v, array['model_key', 'model_id', 'research_model_id', 'model']);
    refcol := case when fkcol in ('model_id', 'research_model_id') then pg_temp.edr_has(m, array['id', 'model_id']) else kcol end;
  end if;
  if fkcol is null or refcol is null then raise exception 'research registry: cannot tell how research_model_versions points at research_models — nothing was registered'; end if;
  vcol := pg_temp.edr_has(v, array['version', 'model_version', 'version_label', 'semver', 'label']);

  for st in select * from jsonb_array_elements(S -> 'studies') loop
    mach := st -> 'machine';
    execute format('select %I::text from %s where %I::text = $1 limit 1', refcol, m, kcol) into ref using st ->> 'id';
    if ref is null then
      mv := jsonb_build_object(kcol, st ->> 'id');
      ncol := pg_temp.edr_has(m, array['name', 'title', 'display_name', 'label']);
      if ncol is not null and ncol <> kcol then mv := mv || jsonb_build_object(ncol, st ->> 'title'); end if;
      foreach c in array array['title', 'display_name'] loop
        if c <> kcol and pg_temp.edr_has(m, array[c]) is not null and not (mv ? c) then mv := mv || jsonb_build_object(c, st ->> 'title'); end if;
      end loop;
      c := pg_temp.edr_has(m, array['sport', 'league']); if c is not null then mv := mv || jsonb_build_object(c, 'NFL'); end if;
      c := pg_temp.edr_has(m, array['sport_key']); if c is not null then mv := mv || jsonb_build_object(c, 'americanfootball_nfl'); end if;
      c := pg_temp.edr_has(m, array['status', 'model_status', 'maturity']); if c is not null then mv := mv || jsonb_build_object(c, pg_temp.edr_label(m, c, array['experimental'])); end if;
      c := pg_temp.edr_has(m, array['provenance', 'evidence_provenance', 'tier', 'evidence_tier']);
      if c is not null then mv := mv || jsonb_build_object(c, pg_temp.edr_label(m, c, array['t3', 'research_model', 'research', 'model'])); end if;
      c := pg_temp.edr_has(m, array['objective', 'goal']); if c is not null then mv := mv || jsonb_build_object(c, st ->> 'objective'); end if;
      c := pg_temp.edr_has(m, array['hypothesis']); if c is not null then mv := mv || jsonb_build_object(c, st ->> 'hypothesis'); end if;
      c := pg_temp.edr_has(m, array['description', 'summary']); if c is not null then mv := mv || jsonb_build_object(c, st ->> 'hypothesis'); end if;
      c := pg_temp.edr_has(m, array['family', 'category', 'module', 'domain']); if c is not null then mv := mv || jsonb_build_object(c, 'nfl_market_structure'); end if;
      c := pg_temp.edr_has(m, array['owner', 'created_by', 'registered_by']); if c is not null then mv := mv || jsonb_build_object(c, S ->> 'registered_at' || ' preregistration'); end if;
      c := pg_temp.edr_has(m, array['metadata', 'meta', 'spec', 'details', 'config']);
      if c is not null then mv := mv || jsonb_build_object(c, pg_temp.edr_val(m, c, null, st || jsonb_build_object('content_sha256', S ->> 'content_sha256'), null)); end if;
      ref := pg_temp.edr_insert(m, mv, refcol);
      n_models := n_models + 1;
    else
      kept := kept + 1;
    end if;

    if vcol is not null then
      execute format('select exists (select 1 from %s where %I::text = $1 and %I::text = $2)', v, fkcol, vcol) into have using ref, mach ->> 'version';
    else
      execute format('select exists (select 1 from %s where %I::text = $1)', v, fkcol) into have using ref;
    end if;
    continue when have;
    vv := jsonb_build_object(fkcol, ref);
    if vcol is not null then vv := vv || jsonb_build_object(vcol, mach ->> 'version'); end if;
    c := pg_temp.edr_has(v, array['status', 'model_status', 'maturity']); if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_label(v, c, array['experimental'])); end if;
    c := pg_temp.edr_has(v, array['provenance', 'evidence_provenance', 'tier']); if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_label(v, c, array['t3', 'research_model', 'research', 'model'])); end if;
    for i in 1 .. 3 loop
      c := pg_temp.edr_has(v, pairs[i:i][1:4]::text[]);
      if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, st ->> (wkeys[i] || '_window'),
        jsonb_build_object('from', mach -> 'window_dates' -> wkeys[i] -> 0, 'to', mach -> 'window_dates' -> wkeys[i] -> 1, 'description', st ->> (wkeys[i] || '_window')),
        mach -> 'window_dates' -> wkeys[i])); end if;
    end loop;
    c := pg_temp.edr_has(v, array['objective', 'goal']); if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, st ->> 'objective', null, null)); end if;
    c := pg_temp.edr_has(v, array['hypothesis']); if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, st ->> 'hypothesis', null, null)); end if;
    c := pg_temp.edr_has(v, array['min_sample', 'minimum_sample', 'min_n', 'sample_target']);
    if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, (st -> 'minimum_sample')::text,
      case when pg_temp.edr_typ(v, c) in ('jsonb', 'json') then st -> 'minimum_sample' else mach -> 'minimum_sample' end, null)); end if;
    c := pg_temp.edr_has(v, array['success_metric', 'primary_metric', 'metric']); if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, st ->> 'primary_metric', null, null)); end if;
    c := pg_temp.edr_has(v, array['promotion_criteria', 'decision_rule', 'criteria', 'success_criteria']);
    if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, st ->> 'decision_rule',
      jsonb_build_object('decision_rule', st -> 'decision_rule', 'frozen_protocol', S -> 'frozen_protocol', 'family_correction', S -> 'family_correction'), null)); end if;
    c := pg_temp.edr_has(v, array['forking_paths', 'forking_paths_disclosure', 'disclosure', 'garden_of_forking_paths']);
    if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, null, st -> 'forking_paths', null)); end if;
    c := pg_temp.edr_has(v, array['spec', 'metadata', 'meta', 'params', 'config', 'details', 'definition', 'protocol']);
    if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c, null, st || jsonb_build_object('content_sha256', S ->> 'content_sha256'), null)); end if;
    c := pg_temp.edr_has(v, array['notes', 'description']);
    if c is not null then vv := vv || jsonb_build_object(c, pg_temp.edr_val(v, c,
      'Preregistered ' || (S ->> 'registered_at') || ': football/market_structure/preregistration.json sha256 ' || (S ->> 'content_sha256') || '. No result until a validation report writes one.', null, null)); end if;
    perform pg_temp.edr_insert(v, vv, fkcol);
    n_versions := n_versions + 1;
  end loop;
  raise notice 'research registry: % model row(s) and % version row(s) written; % study(ies) were already registered and left as they are', n_models, n_versions, kept;
end $reg$;

commit;

-- THE REPORT: each study, as research_model_current reads it. Every row should say ok.
create or replace function pg_temp.edr_report() returns table (piece text, state text)
language plpgsql as $f$
declare id text; j jsonb; k text; s text; p text;
begin
  foreach id in array array[${J.studies.map((s) => "'" + s.id + "'").join(', ')}] loop
    j := null;
    if to_regclass('public.research_model_current') is not null then
      execute 'select to_jsonb(r) from public.research_model_current r where lower(coalesce(to_jsonb(r) ->> ''model_key'', to_jsonb(r) ->> ''key'', to_jsonb(r) ->> ''model_name'', to_jsonb(r) ->> ''model'', to_jsonb(r) ->> ''name'')) = lower($1) limit 1'
        into j using id;
    end if;
    s := lower(coalesce(j ->> 'status', j ->> 'model_status', j ->> 'maturity', ''));
    p := coalesce(j ->> 'passed', 'null');
    piece := id || ' is EXPERIMENTAL with no passing result';
    state := case when to_regclass('public.research_model_current') is null then 'CHECK THIS: research_model_current is not in this database'
                  when j is null then 'CHECK THIS: not in research_model_current'
                  when s <> 'experimental' then 'CHECK THIS: status reads ' || s
                  when p = 'true' then 'CHECK THIS: a result row shows passed = true'
                  else 'ok' end;
    return next;
  end loop;
end $f$;
select * from pg_temp.edr_report();
`;
}

if (require.main === module) {
  const sql = build();
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  if (process.argv.includes('--check')) { if (cur !== sql) { console.log('STALE ' + path.relative(ROOT, OUT) + ' (run node tools/football/build_prereg_sql.js)'); process.exit(1); } console.log('current'); process.exit(0); }
  if (cur === sql) console.log('unchanged ' + path.relative(ROOT, OUT));
  else { fs.writeFileSync(OUT, sql); console.log('wrote ' + path.relative(ROOT, OUT)); }
}
module.exports = { build, OUT, PRE };
