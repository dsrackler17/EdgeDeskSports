// ============================================================================
// EdgeDesk : build the single-file model_predict
//
// The function is 22 modules, which is the right shape to read and to test. But
// the Supabase in-browser function editor is where this project actually
// deploys from, so it also needs to exist as ONE file that can be pasted.
//
// This concatenates the module tree in dependency order and strips the local
// imports. It deliberately does NOT use a minifying bundler: esbuild and
// friends drop comments, and in this codebase the comments carry the reasoning
// — why the market is grouped by event, why career averages are never fitted,
// why RUN_DISPERSION matters. A generated file nobody can read is a worse
// artifact than a long one.
//
// Only three names collide across modules (N_SIM, CONTRACT, pagedSchema) and
// each is renamed per-module below. scripts/bundle.mjs --check re-detects
// collisions, so a new one fails the build instead of producing a file that
// silently redeclares something.
//
//   node scripts/bundle.mjs           write supabase/functions/model_predict/bundled.index.ts
//   node scripts/bundle.mjs --check   fail if the committed bundle is stale
// ============================================================================

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.join(ROOT, "supabase/functions/model_predict");
const OUT = path.join(SRC, "bundled.index.ts");

/** Dependency order. A module may only reference names declared above it at
 *  module-evaluation time — `const` is not hoisted, so this order is load
 *  bearing, not cosmetic. */
const ORDER = [
  "core/types.ts",
  "core/db.ts",
  "core/odds.ts",
  "core/rng.ts",
  "core/names.ts",
  "core/market.ts",
  "core/identity.ts",
  "core/validate.ts",
  "core/elo.ts",
  "core/fit.ts",
  "models/team_loader.ts",
  "models/mlb.ts",
  "models/tennis_engine.ts",
  "models/atp.ts",
  "models/wta.ts",
  "models/ufc.ts",
  "models/nfl.ts",
  "models/wnba.ts",
  "core/registry.ts",
  "core/runner.ts",
  "core/calibrate.ts",
  "index.ts",
];

/** Per-module renames for names that appear in more than one module. */
const RENAMES = {
  "models/mlb.ts": { N_SIM: "MLB_N_SIM", CONTRACT: "MLB_CONTRACT" },
  "models/ufc.ts": { CONTRACT: "UFC_CONTRACT" },
  "models/nfl.ts": { N_SIM: "NFL_N_SIM", CONTRACT: "NFL_CONTRACT" },
  "models/wnba.ts": { N_SIM: "WNBA_N_SIM", CONTRACT: "WNBA_CONTRACT" },
  "core/calibrate.ts": { pagedSchema: "pagedSchemaForCalibration" },
};

const DECL = /^(?:export\s+)?(?:declare\s+)?(?:async\s+)?(?:function|const|let|var|class|interface|type|enum)\s+([A-Za-z_$][\w$]*)/;

/**
 * Drop local imports and re-exports.
 *
 * Re-export statements (`export { buildMarketIndex, ... };`) have to go too:
 * in a bundle the name is already exported by the module that declared it, and
 * a second export of the same name is a duplicate-export SyntaxError rather
 * than a harmless alias.
 */
function strip(src) {
  const lines = src.split("\n");
  const out = [];
  let buf = null;
  for (const line of lines) {
    if (buf === null && /^import\s/.test(line)) {
      buf = [line];
      if (/;\s*$/.test(line)) {
        flush();
      }
      continue;
    }
    if (buf !== null) {
      buf.push(line);
      if (/;\s*$/.test(line)) flush();
      continue;
    }
    if (/^export\s*\{[^}]*\}\s*;?\s*$/.test(line)) continue; // single-line re-export
    out.push(line);
  }
  if (buf !== null) out.push(...buf);
  return out.join("\n");

  function flush() {
    const text = buf.join("\n");
    const local = /from\s+["']\.\.?\//.test(text);
    if (!local) out.push(...buf); // a remote import would be kept; there are none
    buf = null;
  }
}

function applyRenames(src, map) {
  let out = src;
  for (const [from, to] of Object.entries(map ?? {})) {
    out = out.replace(new RegExp(`\\b${from}\\b`, "g"), to);
  }
  return out;
}

function collisions(modules) {
  const seen = new Map();
  for (const { file, code } of modules) {
    for (const line of code.split("\n")) {
      const m = DECL.exec(line);
      if (!m) continue;
      const n = m[1];
      if (!seen.has(n)) seen.set(n, new Set());
      seen.get(n).add(file);
    }
  }
  return [...seen].filter(([, files]) => files.size > 1).map(([n, files]) => `${n} (${[...files].join(", ")})`);
}

const HEADER = `// ============================================================================
// EdgeDesk : model_predict  —  SINGLE-FILE BUILD
//
// GENERATED. Do not edit this file by hand: the next build overwrites it.
// The source of truth is supabase/functions/model_predict/{index,core,models}.ts
// and the tests that pin them. Regenerate with:
//
//     node scripts/bundle.mjs
//
// This exists for one reason: the Supabase in-browser function editor deploys
// one file. Paste this whole file in as \`model_predict\`, Verify-JWT OFF, and
// test with ?dry=1 before running live. If you deploy with the Supabase CLI
// instead, deploy the module tree and ignore this file.
//
// Modules are concatenated in dependency order with local imports stripped.
// Three names collided across modules and were renamed by the build:
// N_SIM -> MLB_N_SIM / NFL_N_SIM / WNBA_N_SIM, CONTRACT -> MLB_CONTRACT /
// UFC_CONTRACT / NFL_CONTRACT / WNBA_CONTRACT, and calibrate's pagedSchema ->
// pagedSchemaForCalibration. Nothing else was altered.
// ============================================================================

`;

const modules = ORDER.map((file) => ({
  file,
  code: applyRenames(strip(fs.readFileSync(path.join(SRC, file), "utf8")), RENAMES[file]),
}));

const dup = collisions(modules);
if (dup.length) {
  console.error("bundle aborted — top-level name collisions:\n  " + dup.join("\n  "));
  console.error("\nAdd a rename for one of them in scripts/bundle.mjs RENAMES.");
  process.exit(1);
}

const body = modules
  .map(({ file, code }) =>
    `// ---------------------------------------------------------------------------\n` +
    `// ${file}\n` +
    `// ---------------------------------------------------------------------------\n` +
    code.replace(/\n{3,}/g, "\n\n").trim() + "\n"
  )
  .join("\n");

const bundled = HEADER + body;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== bundled) {
    console.error("bundled.index.ts is stale. Run: node scripts/bundle.mjs");
    process.exit(1);
  }
  console.log("bundled.index.ts is up to date");
} else {
  fs.writeFileSync(OUT, bundled);
  console.log(`wrote ${path.relative(ROOT, OUT)} — ${modules.length} modules, ${bundled.split("\n").length} lines`);
}
